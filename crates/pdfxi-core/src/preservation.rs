//! Preservation validation for incrementally updated PDFs.
//!
//! An incremental save is only useful if the original bytes really remain an
//! exact prefix, the appended `/Prev` chain still reaches the original revision,
//! and the structures that were promised as preserved did not change. This
//! module performs those checks on raw byte slices without rewriting the file.
//!
//! Text expectations are caller-supplied through [`PageTextSource`], so an
//! accessibility or text-extraction crate can provide its own canonical text
//! without this crate importing it. The default source is [`Document`] itself.
//! Every bound (revision count, policy keys, descriptor lengths) is checked
//! before work is done, and every failure is a typed [`PreservationError`].
//!
//! Long-term packaging and cryptographic signing are deliberately *not*
//! implemented here. [`PreservationOperation::check`] reports them as
//! [`PreservationError::UnsupportedOperation`] rather than pretending a plain
//! PDF byte append is an archival package or a signature.

use crate::content::extract_text;
use crate::object::Object;
use crate::parser::{self, XrefSectionKind};
use crate::{Document, Error, Result};

/// Maximum number of appended revisions a validation will inspect.
pub const MAX_REVISIONS: usize = 64;
/// Maximum number of trailer keys one policy may require as preserved.
pub const MAX_PRESERVED_KEYS: usize = 128;
/// Maximum length of a trailer key name in a policy.
pub const MAX_KEY_LEN: usize = 64;

/// A typed reason preservation validation failed or an operation is unsupported.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum PreservationError {
    /// The updated bytes no longer contain the original bytes as a prefix.
    #[error("updated document does not preserve the original {len} byte prefix")]
    PrefixChanged {
        /// Length of the original document.
        len: usize,
    },
    /// The original document has no readable `startxref` marker.
    #[error("original document has no readable startxref marker")]
    MissingStartXref,
    /// The `/Prev` chain does not link back to the original revision.
    #[error("xref revision {section} does not link to an older section")]
    BrokenChain {
        /// Zero-based position of the newest section whose link was invalid.
        section: usize,
    },
    /// The chain contains more sections than the policy allows.
    #[error("xref chain has {count} revisions, above the {limit} limit")]
    TooManyRevisions {
        /// Revisions found.
        count: usize,
        /// Maximum accepted revisions.
        limit: usize,
    },
    /// A trailer key promised as preserved changed value.
    #[error("preserved trailer key /{key} changed")]
    TrailerKeyChanged {
        /// The trailer key, without its leading slash.
        key: String,
    },
    /// Caller-supplied expected text differs from the updated document.
    #[error("page text changed on page {page}")]
    TextChanged {
        /// Zero-based page index whose text changed.
        page: usize,
    },
    /// The policy asks for too many or too-long preserved keys.
    #[error("preservation policy lists {count} keys, above the {limit} limit")]
    TooManyPreservedKeys {
        /// Keys in the policy.
        count: usize,
        /// Maximum accepted keys.
        limit: usize,
    },
    /// A key name was empty or longer than [`MAX_KEY_LEN`].
    #[error("invalid preserved trailer key: {0}")]
    InvalidPreservedKey(String),
    /// A document could not be read structurally.
    #[error("document is not structurally readable: {0}")]
    MalformedDocument(String),
    /// A requested operation has no library implementation in this crate.
    #[error("unsupported preservation operation: {0}")]
    UnsupportedOperation(&'static str),
}

/// The policies a preservation validation may apply.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PreservationPolicy {
    /// Trailer keys whose values must match the original document.
    ///
    /// `/Size`, `/Prev`, `/ID`, `/Root` and xref-stream keys are deliberately
    /// regenerated by an incremental save and are excluded by default.
    pub preserved_trailer_keys: Vec<String>,
    /// Whether caller-supplied page text is compared to the updated document.
    pub compare_page_text: bool,
    /// Maximum number of appended revisions inspected.
    pub max_revisions: usize,
}

impl Default for PreservationPolicy {
    fn default() -> Self {
        Self {
            preserved_trailer_keys: vec!["Info".to_owned()],
            compare_page_text: true,
            max_revisions: MAX_REVISIONS,
        }
    }
}

impl PreservationPolicy {
    /// Create a policy with no required trailer keys and no text comparison.
    #[must_use]
    pub fn minimal() -> Self {
        Self {
            preserved_trailer_keys: Vec::new(),
            compare_page_text: false,
            max_revisions: MAX_REVISIONS,
        }
    }

    /// Require one additional trailer key to remain unchanged.
    #[must_use]
    pub fn with_preserved_key(mut self, key: impl Into<String>) -> Self {
        self.preserved_trailer_keys.push(key.into());
        self
    }

    /// Select or deselect caller-supplied page-text comparison.
    #[must_use]
    pub const fn with_page_text(mut self, compare: bool) -> Self {
        self.compare_page_text = compare;
        self
    }

    /// Set the maximum number of revisions to inspect.
    #[must_use]
    pub const fn with_max_revisions(mut self, limit: usize) -> Self {
        self.max_revisions = limit;
        self
    }

    /// Check the policy's own bounds before inspecting any bytes.
    ///
    /// # Errors
    ///
    /// Returns a typed error when too many keys are requested, a key is empty
    /// or longer than [`MAX_KEY_LEN`], or the revision limit is zero.
    pub fn validate(&self) -> std::result::Result<(), PreservationError> {
        if self.preserved_trailer_keys.len() > MAX_PRESERVED_KEYS {
            return Err(PreservationError::TooManyPreservedKeys {
                count: self.preserved_trailer_keys.len(),
                limit: MAX_PRESERVED_KEYS,
            });
        }
        for key in &self.preserved_trailer_keys {
            if key.is_empty()
                || key.len() > MAX_KEY_LEN
                || key.starts_with('/')
                || key.contains(char::is_whitespace)
            {
                return Err(PreservationError::InvalidPreservedKey(key.clone()));
            }
        }
        if self.max_revisions == 0 {
            return Err(PreservationError::TooManyRevisions { count: 1, limit: 0 });
        }
        Ok(())
    }
}

/// Caller-supplied expected page text.
///
/// This is the only cross-crate hook in the validator: a caller with a richer
/// extractor can return its canonical text for each page. Returning `None`
/// means the caller has no expectation for that page and the validator skips
/// it, recording that fact in the report.
pub trait PageTextSource {
    /// Return the expected text for zero-based page `index`, when known.
    fn expected_text(&self, index: usize) -> Option<String>;
}

impl PageTextSource for Document {
    fn expected_text(&self, index: usize) -> Option<String> {
        self.page_text(index).ok()
    }
}

/// One appended cross-reference revision.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct RevisionInfo {
    /// Whether the revision used a classic table or an xref stream.
    pub kind: XrefSectionKind,
    /// Byte offset of the section in the updated document.
    pub offset: usize,
    /// Number of entries declared by the section.
    pub entries: usize,
}

/// A deterministic account of a successful preservation validation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PreservationValidationReport {
    /// Number of original bytes verified as an exact prefix.
    pub preserved_prefix_bytes: usize,
    /// Bytes appended after the original document.
    pub appended_bytes: usize,
    /// Appended revisions, newest first.
    pub revisions: Vec<RevisionInfo>,
    /// Number of pages present in both documents.
    pub page_count: usize,
    /// Pages for which caller-supplied text was actually compared.
    pub text_pages_verified: usize,
    /// Trailer keys that were checked and found unchanged, sorted.
    pub preserved_keys: Vec<String>,
}

/// Validate an incremental update against its original byte prefix.
///
/// The check verifies the exact prefix, the `/Prev` chain back to the original
/// `startxref`, the policy's trailer keys, the page count and (optionally)
/// caller-supplied page text. It is deterministic: the same inputs always
/// produce the same report.
///
/// # Errors
///
/// Returns a typed [`PreservationError`] for an invalid policy, a changed
/// prefix, a broken xref chain, a changed preserved key or page text, or a
/// document whose structure cannot be read.
pub fn validate_incremental_preservation(
    original: &[u8],
    updated: &[u8],
    policy: &PreservationPolicy,
    text_source: Option<&dyn PageTextSource>,
) -> std::result::Result<PreservationValidationReport, PreservationError> {
    policy.validate()?;
    if !updated.starts_with(original) {
        return Err(PreservationError::PrefixChanged {
            len: original.len(),
        });
    }
    let original_startxref =
        parser::startxref_offset(original).map_err(|_| PreservationError::MissingStartXref)?;
    let original_structure = parser::parse_document(original)
        .map_err(|error| PreservationError::MalformedDocument(error.to_string()))?;
    let updated_structure = parser::parse_document(updated)
        .map_err(|error| PreservationError::MalformedDocument(error.to_string()))?;
    let report = parser::inspect_xref(updated)
        .map_err(|error| PreservationError::MalformedDocument(error.to_string()))?;

    let original_index = report
        .sections
        .iter()
        .position(|section| section.offset == original_startxref)
        .ok_or(PreservationError::BrokenChain { section: 0 })?;
    for (index, section) in report.sections.iter().enumerate().take(original_index + 1) {
        if let Some(previous) = section.previous {
            let linked = report
                .sections
                .get(index + 1)
                .is_some_and(|older| older.offset == previous);
            if !linked {
                return Err(PreservationError::BrokenChain { section: index });
            }
        }
    }
    let revisions: Vec<RevisionInfo> = report.sections[..original_index]
        .iter()
        .map(|section| RevisionInfo {
            kind: section.kind,
            offset: section.offset,
            entries: section.entries,
        })
        .collect();
    if revisions.is_empty() {
        return Err(PreservationError::BrokenChain { section: 0 });
    }
    if revisions.len() > policy.max_revisions {
        return Err(PreservationError::TooManyRevisions {
            count: revisions.len(),
            limit: policy.max_revisions,
        });
    }

    let original_trailer = original_structure.xref.trailer();
    let updated_trailer = updated_structure.xref.trailer();
    let mut preserved_keys = Vec::new();
    for key in &policy.preserved_trailer_keys {
        let unchanged = if key == "ID" {
            first_id(&original_trailer)
                .zip(first_id(&updated_trailer))
                .is_some_and(|(before, after)| before == after)
        } else {
            original_trailer.get(key) == updated_trailer.get(key)
        };
        if !unchanged {
            return Err(PreservationError::TrailerKeyChanged { key: key.clone() });
        }
        preserved_keys.push(key.clone());
    }
    preserved_keys.sort();

    if original_structure.pages.len() != updated_structure.pages.len() {
        return Err(PreservationError::MalformedDocument(format!(
            "page count changed from {} to {}",
            original_structure.pages.len(),
            updated_structure.pages.len()
        )));
    }
    let mut text_pages_verified = 0usize;
    if policy.compare_page_text
        && let Some(source) = text_source
    {
        for (index, page) in updated_structure.pages.iter().enumerate() {
            let Some(expected) = source.expected_text(index) else {
                continue;
            };
            let bytes = parser::page_content(updated, &updated_structure, page)
                .map_err(|error| PreservationError::MalformedDocument(error.to_string()))?;
            let actual = extract_text(&bytes)
                .map_err(|error| PreservationError::MalformedDocument(error.to_string()))?;
            if actual != expected {
                return Err(PreservationError::TextChanged { page: index });
            }
            text_pages_verified += 1;
        }
    }

    Ok(PreservationValidationReport {
        preserved_prefix_bytes: original.len(),
        appended_bytes: updated.len() - original.len(),
        revisions,
        page_count: updated_structure.pages.len(),
        text_pages_verified,
        preserved_keys,
    })
}

/// Return the first `/ID` byte string in a trailer, when present.
fn first_id(trailer: &crate::object::Dictionary) -> Option<&[u8]> {
    match trailer
        .get("ID")
        .and_then(Object::as_array)
        .and_then(|items| items.first())
    {
        Some(Object::String(bytes)) => Some(bytes.as_slice()),
        _ => None,
    }
}

/// A digital-preservation operation a caller may request.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PreservationOperation {
    /// Structural preservation validation (implemented here).
    Validate,
    /// Cryptographic signing of a revision.
    Sign,
    /// Long-term archival packaging (for example PDF/A-3 with attachments).
    LongTermPackaging,
}

impl PreservationOperation {
    /// Check whether this crate implements `self`.
    ///
    /// # Errors
    ///
    /// Returns [`PreservationError::UnsupportedOperation`] for signing and
    /// long-term packaging. Those belong to the security and application
    /// layers; a plain byte append is neither a signature nor an archive.
    pub const fn check(self) -> std::result::Result<(), PreservationError> {
        match self {
            Self::Validate => Ok(()),
            Self::Sign => Err(PreservationError::UnsupportedOperation(
                "cryptographic signing is not implemented in pdfxi-core",
            )),
            Self::LongTermPackaging => Err(PreservationError::UnsupportedOperation(
                "long-term archival packaging is not implemented in pdfxi-core",
            )),
        }
    }
}

impl Document {
    /// Validate an incremental save of this document against its original bytes.
    ///
    /// This is a convenience wrapper over
    /// [`validate_incremental_preservation`] using this document as the text
    /// source and `policy` for the preserved-key and revision bounds.
    ///
    /// # Errors
    ///
    /// Returns any [`PreservationError`] from the free function, or the stored
    /// structural error of this document.
    pub fn validate_incremental(
        &self,
        updated: &[u8],
        policy: &PreservationPolicy,
    ) -> Result<PreservationValidationReport> {
        let original = self.bytes.as_slice();
        validate_incremental_preservation(original, updated, policy, Some(self))
            .map_err(Error::from)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ObjectId;

    fn fixture() -> Vec<u8> {
        pdfxi_testkit::minimal_pdf()
    }

    fn updated_once(original: &[u8]) -> Vec<u8> {
        let mut doc = Document::from_bytes(original.to_vec()).expect("source parses");
        let id = ObjectId::new(20, 0);
        doc.set_object(id, Object::Integer(11)).expect("stage");
        doc.save_incremental().expect("incremental save")
    }

    fn replace_last(pdf: &[u8], from: &str, to: &str) -> Vec<u8> {
        let text = String::from_utf8(pdf.to_vec()).expect("ASCII fixture");
        let position = text.rfind(from).expect("pattern exists");
        assert_eq!(from.len(), to.len(), "replacement must preserve offsets");
        let mut result = String::with_capacity(text.len());
        result.push_str(&text[..position]);
        result.push_str(to);
        result.push_str(&text[position + from.len()..]);
        result.into_bytes()
    }

    /// Insert text into the final trailer, which sits after the xref table, so
    /// object offsets remain valid even though the file grows.
    fn insert_before_last(pdf: &[u8], marker: &str, insert: &str) -> Vec<u8> {
        let text = String::from_utf8(pdf.to_vec()).expect("ASCII fixture");
        let position = text.rfind(marker).expect("pattern exists");
        let mut result = String::with_capacity(text.len() + insert.len());
        result.push_str(&text[..position]);
        result.push_str(insert);
        result.push_str(&text[position..]);
        result.into_bytes()
    }

    /// Replace the first digit of the final startxref offset with a non-digit,
    /// keeping the file length unchanged so only xref parsing is corrupted.
    fn corrupt_last_startxref_offset(pdf: &[u8]) -> Vec<u8> {
        let marker = b"startxref\n";
        let position = pdf
            .windows(marker.len())
            .rposition(|window| window == marker)
            .expect("startxref marker");
        let digit = position + marker.len();
        assert!(pdf[digit].is_ascii_digit());
        let mut out = pdf.to_vec();
        out[digit] = b'x';
        out
    }

    #[test]
    fn valid_incremental_save_is_accepted() {
        let original = fixture();
        let updated = updated_once(&original);
        let policy = PreservationPolicy::default();
        let doc = Document::from_bytes(original.clone()).expect("source");
        let report = doc
            .validate_incremental(&updated, &policy)
            .expect("preserved update");
        assert_eq!(report.preserved_prefix_bytes, original.len());
        assert_eq!(report.appended_bytes, updated.len() - original.len());
        assert_eq!(report.revisions.len(), 1);
        assert_eq!(report.revisions[0].kind, XrefSectionKind::Classic);
        assert_eq!(report.page_count, 1);
        assert_eq!(report.text_pages_verified, 1);
        assert_eq!(report.preserved_keys, vec!["Info".to_owned()]);
    }

    #[test]
    fn validation_is_deterministic_for_the_same_inputs() {
        let original = fixture();
        let updated = updated_once(&original);
        let policy = PreservationPolicy::default();
        let doc = Document::from_bytes(original).expect("source");
        let first = doc.validate_incremental(&updated, &policy).expect("first");
        let second = doc.validate_incremental(&updated, &policy).expect("second");
        assert_eq!(first, second);
    }

    #[test]
    fn changed_prefix_is_rejected_before_any_parsing() {
        let original = fixture();
        let mut updated = updated_once(&original);
        updated[5] = b'9';
        let policy = PreservationPolicy::minimal();
        let error = validate_incremental_preservation(&original, &updated, &policy, None)
            .expect_err("prefix changed");
        assert_eq!(
            error,
            PreservationError::PrefixChanged {
                len: original.len()
            }
        );
    }

    #[test]
    fn corrupt_updated_xref_is_a_typed_error() {
        let original = fixture();
        let updated = corrupt_last_startxref_offset(&updated_once(&original));
        let error = validate_incremental_preservation(
            &original,
            &updated,
            &PreservationPolicy::minimal(),
            None,
        )
        .expect_err("unreadable xref");
        assert!(matches!(error, PreservationError::MalformedDocument(_)));
    }

    #[test]
    fn broken_prev_chain_is_detected() {
        let original = fixture();
        // Appended bytes without a new xref revision leave no appended section
        // whose /Prev links back to the original, which must be reported as a
        // broken chain even though the original bytes are still an exact prefix.
        let mut broken = original.clone();
        broken.extend_from_slice(b"\n% trailing bytes with no new revision\n");
        let error = validate_incremental_preservation(
            &original,
            &broken,
            &PreservationPolicy::minimal(),
            None,
        )
        .expect_err("chain broken");
        assert!(matches!(error, PreservationError::BrokenChain { .. }));
    }

    #[test]
    fn changed_preserved_trailer_key_is_detected() {
        // Add /Info to the final trailer (after the xref table); an incremental
        // save copies it into the new trailer, where this test changes it.
        let original = insert_before_last(&fixture(), " >>\nstartxref", "/Info 1 0 R ");
        let updated = updated_once(&original);
        let changed = replace_last(&updated, "/Info 1 0 R", "/Info 2 0 R");
        let policy = PreservationPolicy::default();
        let error = validate_incremental_preservation(&original, &changed, &policy, None)
            .expect_err("Info changed");
        assert_eq!(
            error,
            PreservationError::TrailerKeyChanged {
                key: "Info".to_owned()
            }
        );
    }

    struct WrongText;

    impl PageTextSource for WrongText {
        fn expected_text(&self, _index: usize) -> Option<String> {
            Some("not the original text".to_owned())
        }
    }

    #[test]
    fn caller_supplied_text_change_is_detected() {
        let original = fixture();
        let updated = updated_once(&original);
        let policy = PreservationPolicy::default();
        let error =
            validate_incremental_preservation(&original, &updated, &policy, Some(&WrongText))
                .expect_err("text changed");
        assert_eq!(error, PreservationError::TextChanged { page: 0 });
    }

    #[test]
    fn revision_and_key_limits_are_bounded() {
        let original = fixture();
        let updated = updated_once(&original);
        let strict = PreservationPolicy::minimal().with_max_revisions(0);
        let error = validate_incremental_preservation(&original, &updated, &strict, None)
            .expect_err("zero revisions allowed");
        assert!(matches!(error, PreservationError::TooManyRevisions { .. }));

        let mut crowded = PreservationPolicy::minimal();
        for index in 0..=MAX_PRESERVED_KEYS {
            crowded = crowded.with_preserved_key(format!("K{index}"));
        }
        let error = validate_incremental_preservation(&original, &updated, &crowded, None)
            .expect_err("too many keys");
        assert!(matches!(
            error,
            PreservationError::TooManyPreservedKeys { .. }
        ));
        assert!(
            PreservationPolicy::minimal()
                .with_preserved_key("/Bad")
                .validate()
                .is_err()
        );
    }

    #[test]
    fn two_incremental_revisions_form_a_valid_chain() {
        let original = fixture();
        let first = updated_once(&original);
        let mut doc = Document::from_bytes(first.clone()).expect("first revision");
        doc.set_object(ObjectId::new(21, 0), Object::Integer(12))
            .expect("stage second");
        let second = doc.save_incremental().expect("second revision");
        let source = Document::from_bytes(original.clone()).expect("source");
        let report = source
            .validate_incremental(&second, &PreservationPolicy::default())
            .expect("two revisions preserved");
        assert_eq!(report.revisions.len(), 2);
        assert!(
            report
                .revisions
                .iter()
                .all(|r| r.kind == XrefSectionKind::Classic)
        );
        assert!(second.starts_with(&original));
    }

    #[test]
    fn signing_and_packaging_are_honestly_unsupported() {
        assert!(PreservationOperation::Validate.check().is_ok());
        assert_eq!(
            PreservationOperation::Sign.check().expect_err("no signing"),
            PreservationError::UnsupportedOperation(
                "cryptographic signing is not implemented in pdfxi-core"
            )
        );
        assert!(matches!(
            PreservationOperation::LongTermPackaging.check(),
            Err(PreservationError::UnsupportedOperation(_))
        ));
    }
}
