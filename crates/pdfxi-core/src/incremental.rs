//! Configurable incremental saves and preservation reporting.
//!
//! [`Document::save_incremental_with`] appends a new revision to an existing
//! PDF without rewriting its bytes: only object bodies staged through
//! [`Document::set_object`] are serialized, followed by a new cross-reference
//! section whose `/Prev` points at the previous `startxref`. The caller chooses
//! whether the new section is a classic `xref` table or a `/Type /XRef` stream.
//!
//! Because unchanged objects stay in the original byte prefix, unknown catalog
//! entries, page-label number trees and `/Metadata` streams are preserved
//! byte-for-byte unless the caller explicitly stages a replacement. The
//! returned [`PreservationReport`] records which parts were preserved and which
//! were regenerated (the cross-reference section, `/Size`, `/Prev` and the
//! second `/ID` element).
//!
//! The second `/ID` element is derived deterministically from the serialized
//! change set (or from a caller-supplied seed), so repeating a save with the
//! same change set yields byte-identical output. No new dependency is used and
//! no object body is decoded or re-compressed, keeping memory bounded by the
//! source length plus the caller's change set.
//!
//! # Plan and preservation boundary
//!
//! [`IncrementalUpdatePlan`] is a deterministic, inspectable plan — original
//! bytes plus appended objects and an xref/trailer pointing at `/Prev` — that
//! [`validate_incremental_plan`] checks and [`PreservationRangeReport`]
//! summarises as original-byte ranges kept intact. Every failure is a typed
//! [`IncrementalPlanError`] (overlapping or gapped ranges, wrong `/Prev`,
//! missing objects, unsupported operations). Bytes are never written to disk.
//! Cryptographic signing and long-term archival packaging remain with the
//! security lane: [`IncrementalOperation::check`] reports them as
//! [`IncrementalPlanError::UnsupportedOperation`] rather than pretending a
//! plain byte append is a signature or an archive.

use std::collections::BTreeMap;

use crate::object::{Dictionary, Object, ObjectId};
use crate::parser::{self, Structure, XrefSectionKind};
use crate::writer;
use crate::{Document, Error, Result};

/// Options controlling one incremental save.
///
/// `Default` selects a classic `xref` table and a change-set-derived second
/// `/ID` element, which makes repeated saves deterministic.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct IncrementalSaveOptions {
    /// Representation of the appended cross-reference section.
    pub xref_kind: XrefSectionKind,
    /// Optional seed for the regenerated second `/ID` element.
    ///
    /// When `Some`, the 16-byte second element is a deterministic digest of
    /// these bytes. When `None`, it is a digest of the serialized change set and
    /// the `xref_kind`, so the same change set always produces the same value.
    pub id_seed: Option<Vec<u8>>,
}

impl Default for IncrementalSaveOptions {
    fn default() -> Self {
        Self {
            xref_kind: XrefSectionKind::Classic,
            id_seed: None,
        }
    }
}

/// A typed account of what an incremental save preserved and regenerated.
///
/// All fields are deterministic for a given source document and change set.
/// A `true` preservation flag means the corresponding bytes remained in the
/// original prefix untouched; a `false` flag means the caller explicitly
/// staged a replacement for that structure.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PreservationReport {
    /// Object numbers written in the new revision, sorted ascending.
    ///
    /// For an xref-stream revision this includes the generated xref-stream
    /// object itself.
    pub objects_written: Vec<u32>,
    /// Number of in-use source objects left untouched in the original prefix.
    pub unchanged_objects: usize,
    /// Whether the prior trailer's `/Root` was carried over unchanged.
    pub root_preserved: bool,
    /// Whether the prior trailer's `/Info` was carried over unchanged.
    pub info_preserved: bool,
    /// Whether the first `/ID` element was carried over unchanged.
    pub id_first_preserved: bool,
    /// Whether the second `/ID` element was regenerated by this revision.
    pub id_second_regenerated: bool,
    /// Whether unknown catalog entries were left in the original prefix.
    pub catalog_entries_preserved: bool,
    /// Whether the `/PageLabels` number tree was left in the original prefix.
    pub page_labels_preserved: bool,
    /// Whether the `/Metadata` stream bytes were left in the original prefix.
    pub metadata_preserved: bool,
    /// Prior trailer keys (apart from regenerated structural keys) kept verbatim.
    pub preserved_trailer_keys: Vec<String>,
    /// The cross-reference representation that was appended.
    pub xref_kind: XrefSectionKind,
    /// Number of bytes appended after the original document.
    pub appended_bytes: usize,
}

/// The bytes of an incremental revision together with its preservation report.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct IncrementalSaveResult {
    /// The complete document: original bytes followed by the new revision.
    pub bytes: Vec<u8>,
    /// What was preserved and what was regenerated.
    pub report: PreservationReport,
}

/// Two independent FNV-1a 64-bit lanes used to derive a 16-byte identifier
/// without adding a hashing dependency.
struct Fnv128 {
    lane_a: u64,
    lane_b: u64,
}

impl Fnv128 {
    /// Create a hasher with distinct, fixed initial lanes.
    fn new() -> Self {
        Self {
            lane_a: 0xcbf2_9ce4_8422_2325,
            lane_b: 0x9e37_79b9_7f4a_7c15,
        }
    }

    /// Absorb `bytes` into both lanes.
    fn update(&mut self, bytes: &[u8]) {
        const PRIME: u64 = 0x1000_0000_01b3;
        for &byte in bytes {
            let value = u64::from(byte);
            self.lane_a = (self.lane_a ^ value).wrapping_mul(PRIME);
            self.lane_b =
                (self.lane_b.rotate_left(7) ^ value.wrapping_add(0x9e)).wrapping_mul(PRIME);
        }
    }

    /// Return the 16-byte digest, lane A followed by lane B (big-endian).
    fn finish(self) -> Vec<u8> {
        let mut out = Vec::with_capacity(16);
        out.extend_from_slice(&self.lane_a.to_be_bytes());
        out.extend_from_slice(&self.lane_b.to_be_bytes());
        out
    }
}

/// Derive the 16-byte second `/ID` element.
///
/// A caller seed takes precedence; otherwise the digest covers the serialized
/// change set and a tag for the xref representation.
fn deterministic_id(seed: Option<&[u8]>, change_bytes: &[u8], kind: XrefSectionKind) -> Vec<u8> {
    let mut hash = Fnv128::new();
    match seed {
        Some(bytes) => hash.update(bytes),
        None => {
            hash.update(change_bytes);
            let tag: u8 = match kind {
                XrefSectionKind::Classic => 0,
                XrefSectionKind::Stream => 1,
            };
            hash.update(&[tag]);
        }
    }
    hash.finish()
}

/// Return the first element of an `/ID` array when it is a byte string.
///
/// Exposed so callers can inspect the preservation rule independently of a
/// full save; an absent or malformed `/ID` yields `None`.
pub fn first_id_element(trailer: &Dictionary) -> Option<&[u8]> {
    match trailer
        .get("ID")
        .and_then(Object::as_array)
        .and_then(|items| items.first())
    {
        Some(Object::String(bytes)) => Some(bytes.as_slice()),
        _ => None,
    }
}

impl Document {
    /// Return `true` when `number` is already used in this document.
    ///
    /// The check covers in-use, free and compressed entries in the source
    /// cross-reference table as well as object numbers staged through
    /// [`Document::set_object`]. Object number 0 is reserved and always
    /// considered used.
    pub fn is_object_number_used(&self, number: u32) -> bool {
        if number == 0 {
            return true;
        }
        let structure = match self.structure.as_ref() {
            Ok(structure) => structure,
            Err(_) => return self.changes.keys().any(|id| id.number == number),
        };
        structure.xref.all_object_numbers().contains(&number)
            || self.changes.keys().any(|id| id.number == number)
    }

    /// Reject `number` when it is already used, otherwise return it unchanged.
    ///
    /// This is the explicit reuse-rejection counterpart of
    /// [`Document::allocate_object_number`]: it lets callers verify a number
    /// before staging a new object.
    ///
    /// # Errors
    ///
    /// Returns [`Error::ObjectNumberInUse`] when the number is reserved,
    /// present in the source xref (even as a free entry), or staged already.
    pub fn assert_object_number_unused(&self, number: u32) -> Result<u32> {
        if self.is_object_number_used(number) {
            Err(Error::ObjectNumberInUse(number))
        } else {
            Ok(number)
        }
    }

    /// Allocate the next object number without ever reusing an existing one.
    ///
    /// The result is one greater than the largest number in the source xref or
    /// the staged change set, so it can be passed directly to
    /// [`Document::set_object`]. The result is deterministic.
    ///
    /// # Errors
    ///
    /// Returns [`Error::ObjectNumberExhausted`] when no `u32` number remains.
    pub fn allocate_object_number(&self) -> Result<u32> {
        let mut highest = self.changes.keys().map(|id| id.number).max().unwrap_or(0);
        if let Ok(structure) = self.structure.as_ref() {
            for number in structure.xref.all_object_numbers() {
                highest = highest.max(number);
            }
        }
        highest.checked_add(1).ok_or(Error::ObjectNumberExhausted)
    }

    /// Append an incremental revision with caller-selected options.
    ///
    /// Only the objects staged through [`Document::set_object`] are serialized.
    /// The original bytes remain an exact prefix. A new cross-reference section
    /// (classic table or xref stream) points `/Prev` at the original
    /// `startxref`, and its dictionary preserves `/Root`, `/Info`, the first
    /// `/ID` element and any unknown trailer keys while regenerating `/Size`,
    /// `/Prev` and the second `/ID` element.
    ///
    /// The returned [`PreservationReport`] states which structures were left
    /// untouched in the prefix and which were regenerated.
    ///
    /// # Errors
    ///
    /// Returns [`Error::MalformedPriorXref`] when the source cross-reference
    /// layer could not be parsed, [`Error::EncryptedDocument`] for encrypted
    /// input, [`Error::UnsupportedState`] for xref-stream sources, and
    /// serialization errors for staged objects that cannot be encoded.
    pub fn save_incremental_with(
        &self,
        options: &IncrementalSaveOptions,
    ) -> Result<IncrementalSaveResult> {
        let structure = match self.structure.as_ref() {
            Ok(structure) => structure,
            Err(error) => return Err(Error::MalformedPriorXref(error.to_string())),
        };
        let prior_trailer = structure.xref.trailer();
        if prior_trailer.contains_key("Encrypt") {
            return Err(Error::EncryptedDocument);
        }
        if structure.xref.uses_xref_stream {
            return Err(Error::UnsupportedState(
                "cross-reference streams are not supported",
            ));
        }
        let previous = parser::startxref_offset(&self.bytes)
            .map_err(|error| Error::MalformedPriorXref(error.to_string()))?;

        let mut trailer = prior_trailer.clone();
        for (key, value) in &self.trailer_entries {
            trailer.insert(key.clone(), value.clone());
        }
        trailer.remove("XRefStm");
        let root_preserved = prior_trailer.get("Root")
            == Some(&Object::Reference(ObjectId::new(
                structure.root_id.number,
                structure.root_id.generation,
            )));
        trailer.insert("Root".to_owned(), Object::Reference(structure.root_id));
        let info_preserved = match prior_trailer.get("Info") {
            Some(value) => trailer.get("Info") == Some(value),
            None => false,
        };
        let id_first = first_id_element(&prior_trailer).map(|bytes| bytes.to_vec());
        let id_first_preserved = id_first.is_some();

        let mut out = self.bytes.clone();
        out.push(b'\n');
        let revision_start = out.len();

        let mut offsets = BTreeMap::new();
        let mut written = Vec::with_capacity(self.changes.len());
        for (id, object) in &self.changes {
            offsets.insert(id.number, out.len());
            writer::serialize_indirect(*id, object, &mut out)?;
            out.push(b'\n');
            written.push(id.number);
        }
        let change_bytes = &out[revision_start..];

        let second = deterministic_id(options.id_seed.as_deref(), change_bytes, options.xref_kind);
        let first = match id_first {
            Some(bytes) => Object::String(bytes),
            None => Object::String(deterministic_id(None, b"pdfxi-first-id", options.xref_kind)),
        };
        trailer.insert(
            "ID".to_owned(),
            Object::Array(vec![first, Object::String(second)]),
        );

        let highest = written.iter().copied().max().unwrap_or(0);
        let previous_i64 = i64::try_from(previous)
            .map_err(|_| Error::CannotSerialize("previous startxref exceeds i64".to_owned()))?;

        match options.xref_kind {
            XrefSectionKind::Classic => {
                let xref_offset = out.len();
                writer::write_xref_section(&mut out, &offsets, false);
                let size = trailer_size(&trailer, highest);
                trailer.insert("Size".to_owned(), Object::Integer(i64::from(size)));
                trailer.insert("Prev".to_owned(), Object::Integer(previous_i64));
                writer::write_trailer(&mut out, &trailer, xref_offset)?;
            }
            XrefSectionKind::Stream => {
                let xref_number = self.allocate_object_number()?;
                written.push(xref_number);
                written.sort_unstable();
                let size = trailer_size(&trailer, highest.max(xref_number));
                write_xref_stream_section(
                    &mut out,
                    &offsets,
                    &trailer,
                    previous_i64,
                    xref_number,
                    size,
                )?;
            }
        }

        let changed_numbers: Vec<u32> = written.clone();
        let unchanged_objects = structure
            .xref
            .in_use_entries()
            .iter()
            .filter(|(number, _)| !changed_numbers.contains(number))
            .count();
        let regenerated = ["Size", "Root", "Prev", "ID", "XRefStm"];
        let mut preserved_trailer_keys = Vec::new();
        for (key, prior_value) in &prior_trailer {
            if regenerated.contains(&key.as_str()) {
                continue;
            }
            if trailer.get(key) == Some(prior_value) {
                preserved_trailer_keys.push(key.clone());
            }
        }

        let report = PreservationReport {
            objects_written: changed_numbers,
            unchanged_objects,
            root_preserved,
            info_preserved,
            id_first_preserved,
            id_second_regenerated: true,
            catalog_entries_preserved: catalog_entry_untouched(
                structure,
                &self.bytes,
                &self.changes,
                structure.root_id,
            ),
            page_labels_preserved: catalog_child_untouched(
                structure,
                &self.bytes,
                &self.changes,
                "PageLabels",
            ),
            metadata_preserved: catalog_child_untouched(
                structure,
                &self.bytes,
                &self.changes,
                "Metadata",
            ),
            preserved_trailer_keys,
            xref_kind: options.xref_kind,
            appended_bytes: out.len() - self.bytes.len(),
        };

        Ok(IncrementalSaveResult { bytes: out, report })
    }
}

/// Return `true` when the catalog object itself was not staged for replacement.
fn catalog_entry_untouched(
    structure: &Structure,
    bytes: &[u8],
    changes: &BTreeMap<ObjectId, Object>,
    root: ObjectId,
) -> bool {
    if changes.keys().any(|id| id.number == root.number) {
        return false;
    }
    // The catalog was not staged, so its raw bytes remain in the prefix even if
    // this reader cannot decode them for a finer-grained report.
    let _ = (structure, bytes);
    true
}

/// Return `true` when a catalog child (for example `/PageLabels` or
/// `/Metadata`) was not staged for replacement.
fn catalog_child_untouched(
    structure: &Structure,
    bytes: &[u8],
    changes: &BTreeMap<ObjectId, Object>,
    key: &str,
) -> bool {
    let root = structure.root_id;
    if changes.keys().any(|id| id.number == root.number) {
        return false;
    }
    let catalog = match parser::load_object(bytes, &structure.xref, root) {
        Ok(Object::Dictionary(dictionary)) => dictionary,
        _ => return true,
    };
    match catalog.get(key).and_then(Object::as_reference) {
        Some(id) => !changes.keys().any(|staged| staged.number == id.number),
        None => true,
    }
}

/// Compute a `/Size` covering the declared size and the highest written number.
fn trailer_size(trailer: &Dictionary, highest_object: u32) -> u32 {
    let declared = trailer
        .get("Size")
        .and_then(Object::as_i64)
        .filter(|value| *value >= 0)
        .and_then(|value| u32::try_from(value).ok())
        .unwrap_or(0);
    declared.max(highest_object.saturating_add(1)).max(1)
}

/// Append a `/Type /XRef` stream section covering the changed objects.
///
/// Widths `[1 4 0]` describe one type byte and a four-byte big-endian offset
/// per entry. Entry 0 is free; the generated xref-stream object is an in-use
/// type-1 entry pointing at itself, matching ISO 32000 incremental updates.
fn write_xref_stream_section(
    out: &mut Vec<u8>,
    offsets: &BTreeMap<u32, usize>,
    trailer: &Dictionary,
    previous: i64,
    xref_number: u32,
    size: u32,
) -> Result<()> {
    let xref_offset = out.len();
    let mut entries: BTreeMap<u32, u32> = BTreeMap::new();
    entries.insert(0, 0);
    for (number, offset) in offsets {
        let value = u32::try_from(*offset).map_err(|_| {
            Error::CannotSerialize("object offset exceeds the 4-byte xref field".to_owned())
        })?;
        entries.insert(*number, value);
    }
    let xref_value = u32::try_from(xref_offset).map_err(|_| {
        Error::CannotSerialize("xref stream offset exceeds the 4-byte xref field".to_owned())
    })?;
    entries.insert(xref_number, xref_value);

    let mut ranges: Vec<(u32, u32)> = Vec::new();
    for &number in entries.keys() {
        match ranges.last_mut() {
            Some((first, count)) if first.saturating_add(*count) == number => *count += 1,
            _ => ranges.push((number, 1)),
        }
    }

    let mut data = Vec::with_capacity(entries.len() * 5);
    for (number, offset) in &entries {
        let kind: u8 = if *number == 0 { 0 } else { 1 };
        data.push(kind);
        data.extend_from_slice(&offset.to_be_bytes());
    }

    let mut dictionary = trailer.clone();
    dictionary.insert("Type".to_owned(), Object::Name("XRef".to_owned()));
    dictionary.insert("Size".to_owned(), Object::Integer(i64::from(size)));
    dictionary.insert(
        "W".to_owned(),
        Object::Array(vec![
            Object::Integer(1),
            Object::Integer(4),
            Object::Integer(0),
        ]),
    );
    let index_items: Vec<Object> = ranges
        .iter()
        .flat_map(|(first, count)| {
            [
                Object::Integer(i64::from(*first)),
                Object::Integer(i64::from(*count)),
            ]
        })
        .collect();
    dictionary.insert("Index".to_owned(), Object::Array(index_items));
    let length = i64::try_from(data.len())
        .map_err(|_| Error::CannotSerialize("xref stream length exceeds i64".to_owned()))?;
    dictionary.insert("Length".to_owned(), Object::Integer(length));
    dictionary.insert("Prev".to_owned(), Object::Integer(previous));

    out.extend_from_slice(format!("{xref_number} 0 obj\n").as_bytes());
    writer::serialize_object(&Object::Dictionary(dictionary), out)?;
    out.extend_from_slice(b"\nstream\n");
    out.extend_from_slice(&data);
    out.extend_from_slice(b"\nendstream\nendobj\n");
    out.extend_from_slice(b"startxref\n");
    out.extend_from_slice(format!("{xref_offset}\n%%EOF\n").as_bytes());
    Ok(())
}

