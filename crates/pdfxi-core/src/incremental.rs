        let first_hex = b"0102030405060708090A0B0C0D0E0F10";
        let old_second_hex = b"A0A1A2A3A4A5A6A7A8A9AAABACADAEAFA0";
        let mut doc = Document::from_bytes(source.clone()).expect("rich fixture parses");
        doc.set_object(ObjectId::new(9, 0), Object::Integer(3))
