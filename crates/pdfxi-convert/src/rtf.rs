//! Deterministic Rich Text Format (RTF) export from a page/text model.
//!
//! This module writes a small, standards-shaped RTF 1.9 document from
//! pre-extracted page text. It performs no parsing and launches no external
//! converter: the caller supplies [`RtfPage`] values (for example derived from
//! `pdfxi_text::TextPage`) and [`export_rtf`] applies an [`RtfOptions`] plan.
//!
//! # Output contract (all deterministic)
//!
//! 1. The document begins with a fixed header, font table, colour table, and
//!    preamble, in that order. Tables are constants, so identical inputs yield
//!    identical bytes.
//! 2. Pages are written in ascending zero-based page order. Duplicate page
//!    numbers collapse to the last supplied page, matching `crate::export_text`.
//! 3. A `\page` control word separates consecutive pages.
//! 4. Each line of a page's text becomes one RTF paragraph (`\par`). Mixed
//!    `\r\n`, `\n`, and `\r` inputs are all recognized as paragraph breaks.
//! 5. Text is escaped for RTF: `\`, `{`, and `}` are backslash-escaped, tabs
//!    become `\tab `, control characters are dropped, and every non-ASCII
//!    UTF-16 code unit is emitted as a signed `\uN?` escape. Because of this the
//!    generated byte stream is pure ASCII.
//! 6. Structural lines are joined with the configured
//!    [`LineEnding`](crate::LineEnding); the default is a single `\n`.
//! 7. An empty input still produces a valid minimal RTF document (header plus
//!    closing brace) with no paragraphs.

use crate::export_options::{ExportOptionError, ExportPageSelection, LineEnding};
use std::collections::BTreeMap;

/// Fixed RTF header: document version, ANSI encoding, default font.
const RTF_HEADER: &str = "{\\rtf1\\ansi\\deff0";
/// Fixed font table: two named fonts referenced by the preamble.
const RTF_FONT_TABLE: &str =
    "{\\fonttbl{\\f0\\fnil\\fcharset0 Calibri;}{\\f1\\froman\\fcharset0 Georgia;}}";
/// Fixed colour table: black, red, and blue entries.
const RTF_COLOR_TABLE: &str =
    "{\\colortbl;\\red0\\green0\\blue0;\\red255\\green0\\blue0;\\red0\\green0\\blue255;}";
/// Fixed preamble: one Unicode fallback character per `\uN` escape, font 0, 11pt.
const RTF_PREAMBLE: &str = "\\viewkind4\\uc1\\pard\\f0\\fs22";

/// One page of pre-extracted text to write into an RTF document.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RtfPage {
    /// Zero-based page index.
    pub page: usize,
    /// Text content. Each line becomes a paragraph.
    pub text: String,
}

impl RtfPage {
    /// Creates a page from a zero-based index and its text.
    #[must_use]
    pub fn new(page: usize, text: impl Into<String>) -> Self {
        Self {
            page,
            text: text.into(),
        }
    }
}

/// Options controlling an RTF export.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct RtfOptions {
    pages: ExportPageSelection,
    include_page_headers: bool,
    line_ending: LineEnding,
}

impl RtfOptions {
    /// Creates options with conservative defaults: all pages, no page headers,
    /// and [`LineEnding::Lf`].
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Replaces the page selection.
    #[must_use]
    pub fn with_pages(mut self, pages: ExportPageSelection) -> Self {
        self.pages = pages;
        self
    }

    /// Enables or disables a bold one-based page header before each page.
    #[must_use]
    pub fn with_page_headers(mut self, include: bool) -> Self {
        self.include_page_headers = include;
        self
    }

    /// Replaces the separator written between structural lines.
    #[must_use]
    pub fn with_line_ending(mut self, line_ending: LineEnding) -> Self {
        self.line_ending = line_ending;
        self
    }

    /// Returns the configured page selection.
    #[must_use]
    pub fn pages(&self) -> &ExportPageSelection {
        &self.pages
    }

    /// Returns whether page headers are emitted.
    #[must_use]
    pub const fn include_page_headers(&self) -> bool {
        self.include_page_headers
    }

    /// Returns the configured line ending.
    #[must_use]
    pub const fn line_ending(&self) -> LineEnding {
        self.line_ending
    }

    /// Validates the options.
    ///
    /// # Errors
    ///
    /// Returns a typed [`ExportOptionError`] for an invalid page selection.
    pub fn validate(&self) -> Result<(), ExportOptionError> {
        self.pages.validate()
    }
}

/// Splits page text into logical paragraphs on `\r\n`, `\n`, or `\r`.
fn split_paragraphs(text: &str) -> Vec<&str> {
    let mut paragraphs = Vec::new();
    let mut start = 0;
    let bytes = text.as_bytes();
    let mut index = 0;
    while index < bytes.len() {
        match bytes[index] {
            b'\r' => {
                paragraphs.push(&text[start..index]);
                index += if bytes.get(index + 1) == Some(&b'\n') {
                    2
                } else {
                    1
                };
                start = index;
            }
            b'\n' => {
                paragraphs.push(&text[start..index]);
                index += 1;
                start = index;
            }
            _ => {
                // `index` is at a UTF-8 character boundary: it only advances
                // by ASCII break bytes or by a full character length below.
                let ch = match text[index..].chars().next() {
                    Some(ch) => ch,
                    None => break,
                };
                index += ch.len_utf8();
            }
        }
    }
    paragraphs.push(&text[start..]);
    paragraphs
}

/// Escapes one paragraph for inclusion in an RTF document.
///
/// Non-ASCII characters are emitted as signed UTF-16 `\uN?` escapes so the
/// returned string is always ASCII.
fn escape_rtf_text(paragraph: &str) -> String {
    let mut out = String::with_capacity(paragraph.len());
    for ch in paragraph.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '{' => out.push_str("\\{"),
            '}' => out.push_str("\\}"),
            '\t' => out.push_str("\\tab "),
            c if c.is_ascii_graphic() || c == ' ' => out.push(c),
            c if c.is_ascii_control() => {}
            c => {
                let mut units = [0u16; 2];
                for unit in c.encode_utf16(&mut units) {
                    // RTF `\uN` takes a signed 16-bit value. `encode_utf16`
                    // yields mutable references into the scratch buffer.
                    let value = *unit;
                    let signed = if value >= 0x8000 {
                        i32::from(value) - 0x1_0000
                    } else {
                        i32::from(value)
                    };
                    out.push_str("\\u");
                    out.push_str(&signed.to_string());
                    out.push('?');
                }
            }
        }
    }
    out
}

/// Builds the RTF document as a UTF-8 (in practice ASCII) string.
///
/// # Errors
///
/// Returns a typed [`ExportOptionError`] when the options are invalid.
pub fn export_rtf_string(
    pages: impl Iterator<Item = RtfPage>,
    options: &RtfOptions,
) -> Result<String, ExportOptionError> {
    options.validate()?;

    // BTreeMap gives deterministic ascending page order; the last page with a
    // given number wins, which matches the plain-text exporter's behaviour.
    let by_page: BTreeMap<usize, RtfPage> = pages.map(|page| (page.page, page)).collect();

    let mut lines: Vec<String> = vec![
        RTF_HEADER.to_owned(),
        RTF_FONT_TABLE.to_owned(),
        RTF_COLOR_TABLE.to_owned(),
        RTF_PREAMBLE.to_owned(),
    ];

    let mut wrote_page = false;
    for (number, page) in by_page {
        if !options.pages().contains(number) {
            continue;
        }
        if wrote_page {
            lines.push("\\page".to_owned());
        }
        wrote_page = true;
        if options.include_page_headers() {
            lines.push(format!("{{\\b Page {}\\b0}}", number.saturating_add(1)));
        }
        for paragraph in split_paragraphs(&page.text) {
            let escaped = escape_rtf_text(paragraph);
            lines.push(format!("{escaped}\\par"));
        }
    }

    lines.push("}".to_owned());
    Ok(options.line_ending().join(lines))
}

/// Builds the RTF document as bytes.
///
/// The output is pure ASCII because all non-ASCII input is emitted as `\uN?`
/// escapes.
///
/// # Errors
///
/// Returns a typed [`ExportOptionError`] when the options are invalid.
pub fn export_rtf(
    pages: impl Iterator<Item = RtfPage>,
    options: &RtfOptions,
) -> Result<Vec<u8>, ExportOptionError> {
    Ok(export_rtf_string(pages, options)?.into_bytes())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn pages() -> Vec<RtfPage> {
        vec![RtfPage::new(1, "Second"), RtfPage::new(0, "First")]
    }

    #[test]
    fn rtf_header_font_and_colour_tables_are_present_and_stable() {
        let first = export_rtf_string(pages().into_iter(), &RtfOptions::new()).expect("export");
        assert!(first.starts_with("{\\rtf1\\ansi\\deff0\n"), "{first}");
        assert!(
            first.contains("{\\fonttbl{\\f0\\fnil\\fcharset0 Calibri;}"),
            "{first}"
        );
        assert!(
            first.contains("{\\colortbl;\\red0\\green0\\blue0;"),
            "{first}"
        );
        assert!(
            first.contains("\\viewkind4\\uc1\\pard\\f0\\fs22"),
            "{first}"
        );
        assert!(first.ends_with("\n}"), "{first}");
        assert_eq!(
            first,
            export_rtf_string(pages().into_iter(), &RtfOptions::new()).expect("export again")
        );
    }

    #[test]
    fn rtf_orders_pages_ascending_and_writes_page_breaks() {
        let out = export_rtf_string(pages().into_iter(), &RtfOptions::new()).expect("export");
        assert!(out.find("First").expect("first") < out.find("Second").expect("second"));
        assert_eq!(out.matches("\\page").count(), 1, "{out}");
    }

    #[test]
    fn rtf_unicode_uses_signed_utf16_escapes() {
        let out = export_rtf_string(
            std::iter::once(RtfPage::new(0, "café € 𐐀")),
            &RtfOptions::new(),
        )
        .expect("export");
        assert!(out.contains("caf\\u233? "), "{out}");
        assert!(out.contains("\\u8364?"), "{out}");
        // Non-BMP U+10400 becomes the surrogate pair D801, DC00.
        assert!(out.contains("\\u-10239?\\u-9216?"), "{out}");
        assert!(out.is_ascii(), "RTF bytes must be ASCII");
    }

    #[test]
    fn rtf_escapes_special_characters_and_tabs() {
        let out = export_rtf_string(
            std::iter::once(RtfPage::new(0, "a\\b {c} d\te")),
            &RtfOptions::new(),
        )
        .expect("export");
        assert!(out.contains("a\\\\b \\{c\\} d\\tab e"), "{out}");
    }

    #[test]
    fn rtf_paragraph_breaks_are_emitted_for_mixed_newlines() {
        let out = export_rtf_string(
            std::iter::once(RtfPage::new(0, "one\r\ntwo\nthree\rfour")),
            &RtfOptions::new(),
        )
        .expect("export");
        // `\pard` in the preamble also contains the substring `\par`, so count
        // only paragraph control words followed by a line ending.
        assert_eq!(out.matches("\\par\n").count(), 4, "{out}");
    }

    #[test]
    fn rtf_page_headers_and_crlf_line_endings_are_honoured() {
        let options = RtfOptions::new()
            .with_page_headers(true)
            .with_line_ending(LineEnding::CrLf);
        let out = export_rtf_string(pages().into_iter(), &options).expect("export");
        assert!(out.contains("{\\b Page 1\\b0}"), "{out}");
        assert!(out.contains("{\\b Page 2\\b0}"), "{out}");
        assert!(
            !out.replace("\r\n", "").contains('\n'),
            "CRLF output must not contain bare LF"
        );
        assert!(out.contains("\r\n"), "{out}");
    }

    #[test]
    fn rtf_duplicate_pages_use_the_last_text() {
        let out = export_rtf_string(
            vec![RtfPage::new(0, "old"), RtfPage::new(0, "new")].into_iter(),
            &RtfOptions::new(),
        )
        .expect("export");
        assert!(out.contains("new\\par"), "{out}");
        assert!(!out.contains("old"), "{out}");
    }

    #[test]
    fn rtf_page_selection_filters_pages() {
        let options = RtfOptions::new().with_pages(ExportPageSelection::Pages(vec![1]));
        let out = export_rtf_string(pages().into_iter(), &options).expect("export");
        assert!(out.contains("Second"), "{out}");
        assert!(!out.contains("First"), "{out}");
        assert_eq!(out.matches("\\page").count(), 0, "{out}");
    }

    #[test]
    fn rtf_empty_document_is_still_valid() {
        let out = export_rtf_string(std::iter::empty(), &RtfOptions::new()).expect("export");
        assert!(out.starts_with("{\\rtf1"), "{out}");
        assert!(out.ends_with("}"), "{out}");
        assert_eq!(out.matches("\\par\n").count(), 0, "{out}");
    }

    #[test]
    fn rtf_invalid_page_range_is_a_typed_error() {
        let options =
            RtfOptions::new().with_pages(ExportPageSelection::Range { first: 4, last: 2 });
        assert_eq!(
            export_rtf(std::iter::empty(), &options).err(),
            Some(ExportOptionError::InvalidPageRange { first: 4, last: 2 })
        );
    }
}
