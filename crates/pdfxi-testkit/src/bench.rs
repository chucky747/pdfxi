//! Deterministic 500-page PDF fixture for the M1 open benchmark.
//!
//! The M1 exit gate requires opening a 500-page document in under 1.5 s and
//! reaching its first page in under 300 ms. Committing such a file would bloat
//! the repository, so this module builds the bytes on demand from the same
//! in-memory assembly used by the small committed fixtures. Nothing here
//! depends on `pdfxi-core`: the benchmark that measures a real parse lives in
//! `crates/pdfxi-core/examples/bench_open_500.rs`.
//!
//! Every page carries a fixed-width ASCII marker (`PDFXI-BENCH-Pnnnn-OF-0500`)
//! so text extraction after open can be verified, and pages cycle through four
//! realistic media boxes (Letter, A4, Letter landscape and Legal). Output is
//! deterministic: two calls to [`large_pdf`] produce byte-identical vectors.

use std::fs;
use std::io;
use std::path::{Component, Path, PathBuf};

use crate::{PageSpec, build_pdf};

/// Number of pages in the benchmark fixture (the M1 exit-gate requirement).
pub const BENCH_PAGE_COUNT: usize = 500;
/// Documented upper bound for the generated benchmark PDF (2 MiB).
///
/// The fixture is intentionally text-only, so its real size is far smaller,
/// but the cap guards against an accidental change that would make the
/// benchmark unrepresentative or slow to regenerate.
pub const BENCH_SIZE_CAP: usize = 2 * 1024 * 1024;
/// File name of the standard benchmark PDF written under `target/perf/`.
pub const BENCH_FILE_NAME: &str = "bench-500-pages.pdf";

/// Realistic page sizes cycled across the benchmark pages, in PDF points.
const PAGE_SIZES: [(f64, f64); 4] = [
    (612.0, 792.0),   // US Letter portrait
    (595.28, 841.89), // A4 portrait
    (792.0, 612.0),   // US Letter landscape
    (612.0, 1008.0),  // US Legal portrait
];

/// Return the deterministic text marker drawn on zero-based page `index`.
///
/// The marker is fixed-width and ASCII-only, so it survives PDF string
/// escaping unchanged and is easy to find in the generated bytes.
pub fn page_text_marker(index: usize) -> String {
    format!("PDFXI-BENCH-P{:04}-OF-{:04}", index + 1, BENCH_PAGE_COUNT)
}

/// Build the deterministic 500-page benchmark PDF entirely in memory.
///
/// Each page has a distinct [`page_text_marker`] and cycles through the
/// [`PAGE_SIZES`] media boxes. The returned bytes are byte-stable across calls
/// and stay well below [`BENCH_SIZE_CAP`]. No file is written.
pub fn large_pdf() -> Vec<u8> {
    let specs: Vec<PageSpec> = (0..BENCH_PAGE_COUNT)
        .map(|index| {
            let (width, height) = PAGE_SIZES[index % PAGE_SIZES.len()];
            PageSpec::new(&page_text_marker(index), width, height)
        })
        .collect();
    build_pdf(&specs)
}

/// Return the repository's `target/perf/` directory.
///
/// The path is derived from the compile-time crate location, so it resolves to
/// the same workspace directory regardless of which crate calls the helper.
pub fn perf_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .map(|workspace| workspace.join("target").join("perf"))
        .unwrap_or_else(|| PathBuf::from("target").join("perf"))
}

/// Return the canonical destination path for the 500-page benchmark PDF.
pub fn default_500_page_pdf_path() -> PathBuf {
    perf_dir().join(BENCH_FILE_NAME)
}

/// Collapse `.` and `..` components lexically without touching the filesystem.
fn normalize_lexical(path: &Path) -> PathBuf {
    let mut out = PathBuf::new();
    for component in path.components() {
        match component {
            Component::Prefix(prefix) => out.push(prefix.as_os_str()),
            Component::RootDir => out.push(component.as_os_str()),
            Component::CurDir => {}
            Component::ParentDir => {
                out.pop();
            }
            Component::Normal(part) => out.push(part),
        }
    }
    out
}

/// Write the generated 500-page PDF to `path` under `target/perf/`.
///
/// Relative paths are resolved against [`perf_dir`]. The resolved path is
/// normalized and checked before any write, so the fixture can only ever land
/// under `target/perf/` — it is never committed and cannot escape via `..`.
/// Parent directories are created as needed. Returns the bytes written via
/// [`large_pdf`], which the caller may reuse to avoid a second regeneration.
///
/// # Errors
///
/// Returns [`io::ErrorKind::InvalidInput`] when the path is not under
/// `target/perf/`, and propagates filesystem errors from directory creation or
/// writing.
pub fn write_500_page_pdf(path: &Path) -> io::Result<Vec<u8>> {
    let base = normalize_lexical(&perf_dir());
    let candidate = if path.is_absolute() {
        path.to_path_buf()
    } else {
        perf_dir().join(path)
    };
    let target = normalize_lexical(&candidate);
    if target == base || !target.starts_with(&base) {
        return Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            format!("benchmark output must stay under {}", base.display()),
        ));
    }
    if let Some(parent) = target.parent() {
        fs::create_dir_all(parent)?;
    }
    let bytes = large_pdf();
    fs::write(&target, &bytes)?;
    Ok(bytes)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::hash::sha256_hex;

    fn as_text(pdf: &[u8]) -> String {
        String::from_utf8_lossy(pdf).into_owned()
    }

    #[test]
    fn large_pdf_is_deterministic() {
        let first = large_pdf();
        let second = large_pdf();
        assert_eq!(first, second);
        assert_eq!(sha256_hex(&first), sha256_hex(&second));
    }

    #[test]
    fn large_pdf_has_exactly_500_pages() {
        let text = as_text(&large_pdf());
        assert!(text.contains("/Count 500"), "page-tree count missing");
        assert_eq!(
            text.matches("/Type /Page ").count(),
            BENCH_PAGE_COUNT,
            "expected 500 /Page objects"
        );
        // 2 root objects + 2 objects per page + 1 shared font.
        assert_eq!(text.matches(" 0 obj").count(), 2 + 2 * BENCH_PAGE_COUNT + 1);
    }

    #[test]
    fn large_pdf_contains_every_distinct_page_marker() {
        let text = as_text(&large_pdf());
        let markers: Vec<String> = (0..BENCH_PAGE_COUNT).map(page_text_marker).collect();
        for marker in &markers {
            assert!(text.contains(&format!("({marker}) Tj")), "missing {marker}");
        }
        let mut sorted = markers.clone();
        sorted.sort();
        sorted.dedup();
        assert_eq!(sorted.len(), BENCH_PAGE_COUNT, "markers must be distinct");
    }

    #[test]
    fn large_pdf_cycles_through_realistic_page_sizes() {
        let text = as_text(&large_pdf());
        for media_box in [
            "/MediaBox [0 0 612 792]",
            "/MediaBox [0 0 595.28 841.89]",
            "/MediaBox [0 0 792 612]",
            "/MediaBox [0 0 612 1008]",
        ] {
            assert!(text.contains(media_box), "missing {media_box}");
        }
    }

    #[test]
    fn large_pdf_stays_under_the_documented_size_cap() {
        let bytes = large_pdf();
        assert!(!bytes.is_empty());
        assert!(
            bytes.len() < BENCH_SIZE_CAP,
            "benchmark fixture is {} bytes (cap {BENCH_SIZE_CAP})",
            bytes.len()
        );
    }

    #[test]
    fn default_path_is_under_perf_dir() {
        let path = default_500_page_pdf_path();
        assert_eq!(path, perf_dir().join(BENCH_FILE_NAME));
        assert_eq!(
            path.file_name().and_then(|s| s.to_str()),
            Some(BENCH_FILE_NAME)
        );
        assert!(path.starts_with(perf_dir()));
    }

    #[test]
    fn write_500_page_pdf_writes_identical_bytes_under_perf_dir() {
        let path = perf_dir().join("tests").join("bench-500-write-test.pdf");
        let _ = fs::remove_file(&path);
        let written = write_500_page_pdf(&path).expect("write under target/perf");
        assert_eq!(written, large_pdf());
        assert_eq!(fs::read(&path).expect("read back"), written);
        fs::remove_file(&path).expect("cleanup test output");
    }

    #[test]
    fn write_500_page_pdf_rejects_paths_outside_perf_dir() {
        let escaped = perf_dir().join("..").join("escape.pdf");
        let error = write_500_page_pdf(&escaped).expect_err("must reject traversal");
        assert_eq!(error.kind(), io::ErrorKind::InvalidInput);
    }
}
