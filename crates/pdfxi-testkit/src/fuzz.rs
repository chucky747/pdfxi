//! Panic-free entry points shared by the libFuzzer targets and smoke tests.
//!
//! Each [`fuzz_parser`]-style function accepts an arbitrary byte slice and
//! returns a small [`FuzzOutcome`]. The functions are deliberately tiny: they
//! bound the input, call real library code, and discard every result. They
//! never panic, never index without a bounds check, never allocate based on an
//! untrusted length, and never use `unsafe`.
//!
//! The `fuzz/fuzz_targets/*.rs` files are thin libFuzzer wrappers around these
//! functions. When `cargo fuzz` and nightly are unavailable, the
//! `fuzz_smoke` example and the `tests/fuzz_smoke.rs` integration test exercise
//! the exact same functions over committed seeds and seeded pseudo-random
//! input. See `fuzz/README.md` for both run modes and the 24-hour release rule.

use std::collections::BTreeMap;

use pdfxi_core::{
    Document, Filter, FlateParams, ObjectStreamOptions, Predictor, analyze_compatibility,
    decode_stream_with_limit, decode_text_string, extract_text, parse_linearization,
    repair_document,
};
use pdfxi_forms::{
    Form, FormSource, ObjectRef, Pattern, PdfValue, import_fdf, import_xfdf, load_acroform,
    parse_xfdf,
};
use pdfxi_security::{
    InMemorySignatureProvider, SignerIdentifier,
    crypto::{
        aes::decrypt_cbc_no_padding,
        md5::md5,
        rc4::rc4,
        sha::{sha256, sha384},
    },
    der::{DerReader, decode_oid_content, encode_sequence},
    verify_signed_data,
    x509::Certificate,
};

/// Upper bound on the bytes any single fuzz invocation offers to a parser.
///
/// Keeping the bound small makes a smoke run deterministic and fast while still
/// covering header, xref, trailer, and stream boundaries. libFuzzer itself may
/// supply longer inputs; the extra bytes are ignored, not truncated unsafely.
pub const MAX_FUZZ_INPUT: usize = 16 * 1024;

/// Output cap passed to the stream decoder so a decompression bomb cannot make
/// a fuzz iteration allocate unboundedly.
const DECODE_LIMIT: usize = 64 * 1024;

/// Counters returned by every fuzz entry point.
///
/// These make the deterministic smoke tests able to assert that real code was
/// reached (for example, that a committed valid PDF was accepted) without ever
/// requiring the fuzz functions themselves to fail or panic.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct FuzzOutcome {
    /// Number of input bytes actually offered to the parser after bounding.
    pub input_len: usize,
    /// Number of sub-cases that returned a success value.
    pub accepted: usize,
    /// Number of sub-cases that returned a structured error.
    pub rejected: usize,
}

/// Return a bounds-checked prefix of `data`.
fn bounded(data: &[u8]) -> &[u8] {
    let len = data.len().min(MAX_FUZZ_INPUT);
    &data[..len]
}

/// Build the common outcome prefix for a bounded input.
fn outcome_for(data: &[u8]) -> FuzzOutcome {
    FuzzOutcome {
        input_len: data.len(),
        ..FuzzOutcome::default()
    }
}

/// Add one success or failure to `outcome` without interpreting the value.
fn tally<T, E>(outcome: &mut FuzzOutcome, result: Result<T, E>) {
    if result.is_ok() {
        outcome.accepted += 1;
    } else {
        outcome.rejected += 1;
    }
}

/// Exercise the core document parser, classic xref / xref streams, and object
/// streams with arbitrary bytes.
///
/// A validly parsed document is additionally re-saved with object streams and
/// an xref stream, and the generated bytes are parsed again, so both the reader
/// and writer sides of the compressed-object path are covered.
pub fn fuzz_parser(data: &[u8]) -> FuzzOutcome {
    let data = bounded(data);
    let mut outcome = outcome_for(data);

    let parsed = Document::from_bytes(data.to_vec());
    tally(&mut outcome, parsed.as_ref().map(|_| ()));

    if let Ok(document) = parsed
        && let Ok(bytes) = document.save_with_object_streams(&ObjectStreamOptions::default())
    {
        tally(&mut outcome, Document::from_bytes(bytes));
    }

    tally(&mut outcome, repair_document(data).map(|_| ()));
    tally(&mut outcome, parse_linearization(data));

    if analyze_compatibility(data).is_supported() {
        outcome.accepted += 1;
    } else {
        outcome.rejected += 1;
    }

    outcome
}

/// Exercise the bounded stream filter decoder with hostile filter parameters.
///
/// The first four input bytes choose a PNG predictor, color count, component
/// width, and column count. A FlateDecode chain and an intentionally
/// unsupported-filter chain are both attempted, so success and structured-error
/// paths are covered.
pub fn fuzz_filters(data: &[u8]) -> FuzzOutcome {
    let data = bounded(data);
    let mut outcome = outcome_for(data);

    let predictor_value = if data.is_empty() {
        1_i64
    } else {
        i64::from(data[0]) - 128
    };
    let predictor = match Predictor::from_pdf(predictor_value) {
        Some(value) => value,
        None => Predictor::None,
    };
    let colors = if data.len() > 1 {
        u32::from(data[1]) % 4 + 1
    } else {
        1
    };
    let bits = if data.len() > 2 {
        (u32::from(data[2]) % 4 + 1) * 8
    } else {
        8
    };
    let columns = if data.len() > 3 {
        u32::from(data[3]) % 128 + 1
    } else {
        1
    };
    let params = FlateParams::new(predictor, colors, bits, columns);

    tally(
        &mut outcome,
        decode_stream_with_limit(data, &[Filter::FlateDecode(params)], DECODE_LIMIT),
    );
    tally(
        &mut outcome,
        decode_stream_with_limit(
            data,
            &[Filter::FlateDecode(params), Filter::RunLengthDecode],
            DECODE_LIMIT,
        ),
    );
    tally(
        &mut outcome,
        decode_stream_with_limit(data, &[], DECODE_LIMIT),
    );

    outcome
}

/// Exercise the content-stream tokenizer and text decoder.
pub fn fuzz_content(data: &[u8]) -> FuzzOutcome {
    let data = bounded(data);
    let mut outcome = outcome_for(data);

    tally(&mut outcome, extract_text(data));

    // `decode_text_string` is total; count it as a covered sub-case.
    let _ = decode_text_string(data);
    outcome.accepted += 1;

    outcome
}

/// Exercise FDF/XFDF parsing, validation patterns, and AcroForm field loading.
pub fn fuzz_forms(data: &[u8]) -> FuzzOutcome {
    let data = bounded(data);
    let mut outcome = outcome_for(data);
    let text = match std::str::from_utf8(data) {
        Ok(value) => value,
        Err(error) => {
            // Invalid UTF-8 is a rejected sub-case, not a reason to stop.
            let _ = error.valid_up_to();
            outcome.rejected += 1;
            ""
        }
    };

    tally(&mut outcome, parse_xfdf(text));
    tally(&mut outcome, import_xfdf(text, &Form::new()));
    tally(&mut outcome, import_fdf(text));

    let pattern: String = text.chars().take(512).collect();
    tally(&mut outcome, Pattern::parse(&pattern));

    let source = ByteFormSource::new(data);
    tally(&mut outcome, load_acroform(&source));

    outcome
}

/// Exercise RC4, AES, hashes, DER, X.509, and CMS SignedData parsing.
pub fn fuzz_crypto(data: &[u8]) -> FuzzOutcome {
    let data = bounded(data);
    let mut outcome = outcome_for(data);

    let _ = md5(data);
    let _ = sha256(data);
    let _ = sha384(data);
    outcome.accepted += 3;

    let first = if data.is_empty() { 0_u8 } else { data[0] };
    let key_len = match first % 3 {
        0 => 16,
        1 => 24,
        _ => 32,
    };
    let mut key = [0_u8; 32];
    let key_bytes = key_len.min(data.len());
    key[..key_bytes].copy_from_slice(&data[..key_bytes]);
    let key_slice = &key[..key_len];

    let mut iv = [0_u8; 16];
    let iv_bytes = 16.min(data.len() - key_bytes);
    iv[..iv_bytes].copy_from_slice(&data[key_bytes..key_bytes + iv_bytes]);
    let payload_start = key_bytes + iv_bytes;

    let _ = rc4(key_slice, data);
    tally(
        &mut outcome,
        decrypt_cbc_no_padding(key_slice, &iv, &data[payload_start..]),
    );

    tally(&mut outcome, Certificate::parse(data));
    tally(&mut outcome, decode_oid_content(data));

    let mut reader = DerReader::new(data);
    let mut read = 0_usize;
    while read < 128 && reader.remaining() > 0 {
        if reader.read_tlv().is_err() {
            break;
        }
        read += 1;
    }
    if read > 0 {
        outcome.accepted += 1;
    } else {
        outcome.rejected += 1;
    }

    let issuer = encode_sequence(&[]);
    let certificate = encode_sequence(&[]);
    if let Ok(signer) = SignerIdentifier::new(issuer, 1)
        && let Ok(provider) = InMemorySignatureProvider::new(signer, certificate, "fuzz")
    {
        tally(&mut outcome, verify_signed_data(data, &provider));
    }

    outcome
}

/// A bounded [`FormSource`] that derives a hostile AcroForm tree from bytes.
///
/// Names, values, and flags come straight from the fuzz input, and odd bytes
/// add `/Kids` references whose indices wrap, exercising the loader's cycle
/// detection. All sizes are fixed, so adversarial input cannot grow the tree
/// without bound.
struct ByteFormSource {
    fields: Vec<PdfValue>,
}

impl ByteFormSource {
    /// Build at most eight field dictionaries from `data`.
    fn new(data: &[u8]) -> Self {
        const MAX_FIELDS: usize = 8;
        let mut fields = Vec::with_capacity(MAX_FIELDS);
        for index in 0..MAX_FIELDS {
            let start = index * 7;
            if start >= data.len() {
                break;
            }
            let seed = data[start];
            let name_len = (usize::from(seed) % 8) + 1;
            let name_end = (start + name_len).min(data.len());
            let name = String::from_utf8_lossy(&data[start..name_end]).into_owned();

            let mut dictionary = BTreeMap::new();
            dictionary.insert("T".to_owned(), PdfValue::Name(name));
            let field_type = match seed.wrapping_mul(3) % 3 {
                0 => "Tx",
                1 => "Btn",
                _ => "Ch",
            };
            dictionary.insert("FT".to_owned(), PdfValue::Name(field_type.to_owned()));
            dictionary.insert(
                "V".to_owned(),
                PdfValue::Text(String::from_utf8_lossy(&data[start..name_end]).into_owned()),
            );
            let flag = f64::from(seed % 16);
            dictionary.insert("Ff".to_owned(), PdfValue::Number(flag));

            if seed & 1 == 1 {
                let target = ((index + 1) % MAX_FIELDS) as u32;
                dictionary.insert(
                    "Kids".to_owned(),
                    PdfValue::Array(vec![PdfValue::Reference(ObjectRef::new(target, 0))]),
                );
            }
            fields.push(PdfValue::Dictionary(dictionary));
        }
        Self { fields }
    }
}

impl FormSource for ByteFormSource {
    fn catalog(&self) -> PdfValue {
        let mut acroform = BTreeMap::new();
        acroform.insert("Fields".to_owned(), PdfValue::Array(self.fields.clone()));
        let mut catalog = BTreeMap::new();
        catalog.insert("AcroForm".to_owned(), PdfValue::Dictionary(acroform));
        PdfValue::Dictionary(catalog)
    }

    fn resolve(&self, value: &PdfValue) -> Option<PdfValue> {
        match value {
            PdfValue::Reference(reference) => {
                let divisor = self.fields.len().max(1);
                let index = reference.number as usize % divisor;
                self.fields.get(index).cloned()
            }
            other => Some(other.clone()),
        }
    }
}
