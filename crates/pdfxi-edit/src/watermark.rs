//! Typed watermark and page-background model.
//!
//! This module is renderer-agnostic and dependency-free. It describes a
//! watermark or background as a validated [`Watermark`], renders one
//! self-contained PDF content-stream overlay per page with
//! [`render_watermark`], and provides copy-on-write helpers for composing that
//! overlay with existing page content ([`compose_content`]) and for merging the
//! resources it needs into a page's resource dictionary
//! ([`apply_resource_patch`]).
//!
//! # Coordinate model
//!
//! Watermark positions are expressed in **display coordinates**: the origin is
//! the lower-left corner of the page as it appears to a reader, `x` grows right
//! and `y` grows up. [`transform_for_page`] supplies the `cm` matrix that maps
//! those display coordinates into the page's
//! unrotated default user space, accounting for both a non-zero MediaBox origin
//! and the page's `/Rotate` value. Each mark is then drawn through a second
//! `cm` that translates, rotates, and scales the mark about its placement
//! point. The two transforms are applied in the correct order because the page
//! transform is emitted first and becomes the base CTM; PDF's `cm` operator
//! concatenates each later matrix in front of the accumulated CTM, so the mark
//! matrix acts in display space before the page matrix maps it to user space.
//!
//! # Additive composition
//!
//! Existing page content is never parsed, rewritten, or mutated.
//! [`compose_content`] returns a fresh byte vector and either prepends the
//! overlay (background, [`Placement::Behind`]) or appends it (watermark,
//! [`Placement::Front`]). Graphics state is balanced with `q`/`Q`, so the
//! overlay cannot leak transforms or alpha into neighbouring content.
//!
//! # Alpha
//!
//! Non-opaque marks reference an ExtGState resource that sets both the stroking
//! (`CA`) and non-stroking (`ca`) alpha constants. The generated resource is
//! described by [`ResourcePatch`], which [`apply_resource_patch`] merges into a
//! page's `Resources` dictionary without dropping existing entries or unknown
//! keys.

