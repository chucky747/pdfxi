/// Describes the resources a [`WatermarkOverlay`] expects on the page.
#[derive(Clone, Debug, PartialEq)]
pub struct ResourcePatch {
    fonts: Vec<ResourceFont>,
    ext_gstates: Vec<ResourceExtGState>,
    required_xobjects: Vec<String>,
}

impl ResourcePatch {
    /// Fonts that must be present after the patch is applied.
    pub fn fonts(&self) -> &[ResourceFont] {
        &self.fonts
    }

    /// ExtGState resources that must be present after the patch is applied.
    pub fn ext_gstates(&self) -> &[ResourceExtGState] {
        &self.ext_gstates
    }

    /// Image XObjects the overlay references by name.
    pub fn required_xobjects(&self) -> &[String] {
        &self.required_xobjects
    }

    /// Returns `true` when the patch adds no resources.
    pub fn is_empty(&self) -> bool {
        self.fonts.is_empty() && self.ext_gstates.is_empty() && self.required_xobjects.is_empty()
    }
}

/// A generated overlay stream and the resources it references.
#[derive(Clone, Debug, PartialEq)]
pub struct WatermarkOverlay {
    content: String,
    fonts: Vec<(String, StandardFont)>,
    alpha: Option<(String, f32)>,
    required_xobjects: Vec<String>,
}

impl WatermarkOverlay {
    /// Returns an empty overlay (used for suppressed pages).
    fn empty() -> Self {
        Self {
            content: String::new(),
            fonts: Vec::new(),
            alpha: None,
            required_xobjects: Vec::new(),
        }
    }

    /// Returns the content-stream bytes.
    pub fn content_bytes(&self) -> &[u8] {
        self.content.as_bytes()
    }

    /// Returns the content stream as text (it is always ASCII).
    pub fn content_str(&self) -> &str {
        &self.content
    }

    /// Returns `(resource name, base font)` pairs in deterministic order.
    pub fn fonts(&self) -> &[(String, StandardFont)] {
        &self.fonts
    }

    /// Returns `(resource name, opacity)` for the alpha ExtGState, if any.
    pub fn alpha(&self) -> Option<(&str, f32)> {
        self.alpha
            .as_ref()
            .map(|(name, opacity)| (name.as_str(), *opacity))
    }

    /// Builds the resource patch that accompanies this overlay.
    pub fn resource_patch(&self) -> ResourcePatch {
        ResourcePatch {
            fonts: self
                .fonts
                .iter()
                .map(|(name, base_font)| ResourceFont {
                    name: name.clone(),
                    base_font: *base_font,
                })
                .collect(),
            ext_gstates: self
                .alpha
                .iter()
                .map(|(name, opacity)| ResourceExtGState {
                    name: name.clone(),
                    opacity: *opacity,
                })
                .collect(),
            required_xobjects: self.required_xobjects.clone(),
        }
    }

    /// Returns `true` when the overlay draws nothing.
    pub fn is_empty(&self) -> bool {
        self.content.is_empty()
    }
}

/// Renders the overlay for one page.
///
/// The function validates the watermark, rejects an out-of-range page index,
/// returns an empty overlay when suppression rules exclude the page, and
/// otherwise emits a self-contained content stream wrapped in balanced
/// graphics state. Existing page content is never read or modified.
pub fn render_watermark(
    watermark: &Watermark,
    page: &PageGeometry,
    page_index: usize,
    page_count: usize,
) -> Result<WatermarkOverlay, WatermarkError> {
    watermark.validate()?;
    PageIndex::new(page_index).checked_for(page_count)?;

    if !watermark.includes_page(page_index) {
        return Ok(WatermarkOverlay::empty());
    }

    let (display_width, display_height) = display_dimensions(page);
    let placements = watermark.placements(display_width, display_height)?;

    let page_matrix: ContentMatrix = transform_for_page(page);
    let style = watermark.style;

    let mut fonts: Vec<(String, StandardFont)> = Vec::new();
    let mut alpha: Option<(String, f32)> = None;
    let mut required_xobjects: Vec<String> = Vec::new();

    let mut content = String::new();
    content.push_str("q\n");
    content.push_str(&page_matrix.to_pdf());
    content.push_str(" cm\n");

    if style.opacity < 1.0 {
        let name = format!("{RESOURCE_PREFIX}GS1");
        content.push_str(&format!("/{name} gs\n"));
        alpha = Some((name, style.opacity));
    }

    let theta = watermark.effective_rotation_degrees().to_radians();
    let (sin, cos) = theta.sin_cos();
    let scale = watermark.scale;
    let matrix_a = format_num(scale * cos);
    let matrix_b = format_num(scale * sin);
    let matrix_c = format_num(-scale * sin);
    let matrix_d = format_num(scale * cos);

    let color = style.color;
    let rgb = format!(
        "{} {} {} rg",
        format_num(f32::from(color.r()) / 255.0),
        format_num(f32::from(color.g()) / 255.0),
        format_num(f32::from(color.b()) / 255.0)
    );

    let text_font_name = format!("{RESOURCE_PREFIX}F1");

    for (tx, ty) in placements {
        content.push_str("q\n");
        content.push_str(&format!(
            "{} {} {} {} {} {} cm\n",
            matrix_a,
            matrix_b,
            matrix_c,
            matrix_d,
            format_num(tx),
            format_num(ty)
        ));

        match &watermark.content {
            MarkContent::Text(text) => {
                if fonts.is_empty() {
                    fonts.push((text_font_name.clone(), style.font));
                }
                let width = approximate_width(text, style);
                let x = -width / 2.0;
                let y = -style.font_size / 2.0;
                let escaped = escape_literal(text);
                content.push_str("BT\n");
                content.push_str(&format!(
                    "/{} {} Tf\n",
                    text_font_name,
                    format_num(style.font_size)
                ));
                content.push_str(&rgb);
                content.push('\n');
                content.push_str(&format!("{} {} Td\n", format_num(x), format_num(y)));
                content.push_str(&format!("({escaped}) Tj\n"));
                content.push_str("ET\n");
            }
            MarkContent::Vector(shape) => {
                let half_w = -shape.width / 2.0;
                let half_h = -shape.height / 2.0;
                content.push_str(&rgb);
                content.push('\n');
                if shape.filled {
                    content.push_str(&format!(
                        "{} {} {} {} re f\n",
                        format_num(half_w),
                        format_num(half_h),
                        format_num(shape.width),
                        format_num(shape.height)
                    ));
                } else {
                    content.push_str("1 w\n");
                    content.push_str(&format!(
                        "{} {} {} {} re S\n",
                        format_num(half_w),
                        format_num(half_h),
                        format_num(shape.width),
                        format_num(shape.height)
                    ));
                }
            }
            MarkContent::Image(image) => {
                if !required_xobjects.contains(&image.xobject_name) {
                    required_xobjects.push(image.xobject_name.clone());
                }
                let half_w = -image.width / 2.0;
                let half_h = -image.height / 2.0;
                content.push_str("q\n");
                content.push_str(&format!(
                    "{} 0 0 {} {} {} cm\n",
                    format_num(image.width),
                    format_num(image.height),
                    format_num(half_w),
                    format_num(half_h)
                ));
                content.push_str(&format!("/{} Do\n", image.xobject_name));
                content.push_str("Q\n");
            }
        }

        content.push_str("Q\n");
    }

    content.push_str("Q\n");

    Ok(WatermarkOverlay {
        content,
        fonts,
        alpha,
        required_xobjects,
    })
}

/// Applies one watermark to every page of a page set in input order.
///
/// The watermark is validated once and the page count is taken from
/// `pages.len()`. The returned vector has exactly one entry per input page;
/// pages excluded by the watermark's range/suppression rules receive an empty
/// [`WatermarkOverlay`]. Output is deterministic for identical inputs, and no
/// page geometry or existing content is mutated.
pub fn render_watermark_page_set(
    watermark: &Watermark,
    pages: &[PageGeometry],
) -> Result<Vec<WatermarkOverlay>, WatermarkError> {
    watermark.validate()?;
    let page_count = pages.len();
    let mut overlays = Vec::with_capacity(page_count);
    for (page_index, page) in pages.iter().enumerate() {
        overlays.push(render_watermark(watermark, page, page_index, page_count)?);
    }
    Ok(overlays)
}

/// Returns a fresh byte vector combining `existing` with `overlay`.
///
/// For [`Placement::Front`] the overlay is appended after the existing
/// content; for [`Placement::Behind`] it is prepended so that existing content
/// paints on top. The input slice is copied and never mutated. If the overlay
/// is empty, a verbatim copy of `existing` is returned.
pub fn compose_content(
    existing: &[u8],
    overlay: &WatermarkOverlay,
    placement: Placement,
) -> Vec<u8> {
    if overlay.is_empty() {
        return existing.to_vec();
    }
    let mut combined = Vec::with_capacity(existing.len() + 1 + overlay.content.len());
    match placement {
        Placement::Front => {
            combined.extend_from_slice(existing);
            combined.push(b'\n');
            combined.extend_from_slice(overlay.content_bytes());
        }
        Placement::Behind => {
            combined.extend_from_slice(overlay.content_bytes());
            combined.push(b'\n');
            combined.extend_from_slice(existing);
        }
    }
    combined
}

/// Merges an overlay's resources into a page resource dictionary.
///
/// The input dictionary is cloned, so every existing key — including keys this
/// module does not understand — is preserved verbatim. Generated font and
/// ExtGState entries are added under their deterministic names; a name that is
/// already present on the page is reported as
/// [`WatermarkError::ResourceNameCollision`] instead of being overwritten.
/// Image marks require their XObject to already exist under `/XObject`.
pub fn apply_resource_patch(
    resources: &Dict,
    patch: &ResourcePatch,
) -> Result<Dict, WatermarkError> {
    let mut result = resources.clone();

    for font in &patch.fonts {
        let mut fonts = take_dict(&result, "Font")?;
        if fonts.contains_key(&font.name) {
            return Err(WatermarkError::ResourceNameCollision {
                name: font.name.clone(),
            });
        }
        let mut entry = Dict::new();
        entry.insert("Type".to_string(), Value::Name("Font".to_string()));
        entry.insert("Subtype".to_string(), Value::Name("Type1".to_string()));
        entry.insert(
            "BaseFont".to_string(),
            Value::Name(font.base_font.base_name().to_string()),
        );
        fonts.insert(font.name.clone(), Value::Dictionary(entry));
        result.insert("Font".to_string(), Value::Dictionary(fonts));
    }

    for state in &patch.ext_gstates {
        let mut states = take_dict(&result, "ExtGState")?;
        if states.contains_key(&state.name) {
            return Err(WatermarkError::ResourceNameCollision {
                name: state.name.clone(),
            });
        }
        let mut entry = Dict::new();
        entry.insert("Type".to_string(), Value::Name("ExtGState".to_string()));
        entry.insert("ca".to_string(), Value::Real(f64::from(state.opacity)));
        entry.insert("CA".to_string(), Value::Real(f64::from(state.opacity)));
        states.insert(state.name.clone(), Value::Dictionary(entry));
        result.insert("ExtGState".to_string(), Value::Dictionary(states));
    }

    for name in &patch.required_xobjects {
        let present = match result.get("XObject") {
            Some(Value::Dictionary(xobjects)) => xobjects.contains_key(name),
            _ => false,
        };
        if !present {
            return Err(WatermarkError::MissingXObject { name: name.clone() });
        }
    }

    Ok(result)
}

/// Returns a clone of the named dictionary sub-entry, or a fresh dictionary
/// when the key is absent. A present non-dictionary value is an error.
fn take_dict(resources: &Dict, key: &'static str) -> Result<Dict, WatermarkError> {
    match resources.get(key) {
        None => Ok(Dict::new()),
        Some(Value::Dictionary(dict)) => Ok(dict.clone()),
        Some(_) => Err(WatermarkError::InvalidResourceCategory(key)),
    }
}

