/// Prefix for resource names generated by this module.
///
/// Names are deterministic (`PxiWmF1`, `PxiWmGS1`, ...) and chosen to be
/// unlikely to collide with existing page resources. A collision is reported as
/// [`WatermarkError::ResourceNameCollision`] rather than silently overwriting
/// a caller's resource.
const RESOURCE_PREFIX: &str = "PxiWm";

/// Upper bound on the number of marks a single tiled overlay may emit.
///
/// This bounds memory use when a page has a very large MediaBox and a very
/// small tile spacing.
const MAX_MARKS: usize = 100_000;

/// Errors produced while validating or rendering a [`Watermark`].
#[derive(Debug, Clone, PartialEq)]
pub enum WatermarkError {
    /// Font size was not finite, was non-positive, or was unreasonably large.
    InvalidFontSize(f32),
    /// Opacity was not finite or lay outside `0.0..=1.0`.
    InvalidOpacity(f32),
    /// Scale was not finite or was non-positive.
    InvalidScale(f32),
    /// Rotation was not finite or exceeded 360 degrees in magnitude.
    InvalidRotation(f32),
    /// Tile spacing on an axis was not finite or was smaller than one point.
    InvalidTileSpacing {
        /// Axis whose spacing was invalid (`"x"` or `"y"`).
        axis: &'static str,
        /// The rejected value.
        value: f32,
    },
    /// A coordinate or dimension was not finite.
    InvalidCoordinate {
        /// Name of the offending field.
        field: &'static str,
        /// The rejected value.
        value: f32,
    },
    /// A vector mark had a non-finite or non-positive dimension.
    InvalidVectorSize {
        /// Name of the offending field.
        field: &'static str,
        /// The rejected value.
        value: f32,
    },
    /// An image XObject resource name was empty or contained invalid bytes.
    InvalidImageName(String),
    /// A page range had its first page after its last page.
    InvalidPageRange {
        /// First page index.
        first: usize,
        /// Last page index.
        last: usize,
    },
    /// A text mark carried an empty string.
    EmptyText,
    /// A tiled placement would exceed the implementation's mark limit.
    TooManyMarks {
        /// Number of marks that would have been emitted.
        count: usize,
    },
    /// The requested page index was outside the document.
    PageOutOfRange {
        /// Rejected zero-based page index.
        index: usize,
        /// Number of pages in the document.
        page_count: usize,
    },
    /// A generated resource name collided with an existing resource.
    ResourceNameCollision {
        /// The colliding resource name.
        name: String,
    },
    /// A required image XObject was absent from the page resources.
    MissingXObject {
        /// Name of the missing XObject.
        name: String,
    },
    /// An existing resource category had the wrong dictionary shape.
    InvalidResourceCategory(&'static str),
    /// An underlying geometry value was invalid.
    Geometry(GeometryError),
}

impl fmt::Display for WatermarkError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::InvalidFontSize(value) => {
                write!(
                    f,
                    "font size must be finite, positive, and at most 4096 points, got {value}"
                )
            }
            Self::InvalidOpacity(value) => {
                write!(
                    f,
                    "opacity must be finite and within 0.0..=1.0, got {value}"
                )
            }
            Self::InvalidScale(value) => {
                write!(f, "scale must be finite and positive, got {value}")
            }
            Self::InvalidRotation(value) => {
                write!(
                    f,
                    "rotation must be finite and within -360..=360 degrees, got {value}"
                )
            }
            Self::InvalidTileSpacing { axis, value } => {
                write!(
                    f,
                    "tile spacing `{axis}` must be finite and at least 1 point, got {value}"
                )
            }
            Self::InvalidCoordinate { field, value } => {
                write!(f, "coordinate `{field}` must be finite, got {value}")
            }
            Self::InvalidVectorSize { field, value } => {
                write!(
                    f,
                    "vector `{field}` must be finite and positive, got {value}"
                )
            }
            Self::InvalidImageName(name) => {
                write!(
                    f,
                    "image XObject name `{name}` must be a non-empty PDF name without delimiters"
                )
            }
            Self::InvalidPageRange { first, last } => {
                write!(
                    f,
                    "page range first index {first} exceeds last index {last}"
                )
            }
            Self::EmptyText => f.write_str("a text watermark must contain a non-empty string"),
            Self::TooManyMarks { count } => {
                write!(
                    f,
                    "tiled watermark would emit {count} marks, exceeding the limit"
                )
            }
            Self::PageOutOfRange { index, page_count } => {
                write!(
                    f,
                    "page index {index} is outside a document of {page_count} pages"
                )
            }
            Self::ResourceNameCollision { name } => {
                write!(
                    f,
                    "generated resource name `{name}` already exists on the page"
                )
            }
            Self::MissingXObject { name } => {
                write!(
                    f,
                    "required image XObject `/{name}` is missing from page resources"
                )
            }
            Self::InvalidResourceCategory(key) => {
                write!(f, "resource category `/{key}` is not a dictionary")
            }
            Self::Geometry(err) => write!(f, "watermark geometry error: {err}"),
        }
    }
}

impl std::error::Error for WatermarkError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Geometry(err) => Some(err),
            _ => None,
        }
    }
}

impl From<GeometryError> for WatermarkError {
    fn from(err: GeometryError) -> Self {
        Self::Geometry(err)
    }
}

/// Whether a watermark is painted in front of or behind existing content.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Placement {
    /// Paint after existing content (a traditional stamp/watermark on top).
    Front,
    /// Paint before existing content (a page background).
    Behind,
}

/// Pages a watermark applies to, expressed as zero-based page indices.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub enum PageRange {
    /// Every page in the document.
    #[default]
    All,
    /// An inclusive range of zero-based page indices.
    RangeInclusive {
        /// First page index.
        first: usize,
        /// Last page index (inclusive).
        last: usize,
    },
    /// An explicit list of zero-based page indices.
    List(Vec<usize>),
}

impl PageRange {
    /// Returns `true` when `page_index` is selected.
    pub fn contains(&self, page_index: usize) -> bool {
        match self {
            Self::All => true,
            Self::RangeInclusive { first, last } => page_index >= *first && page_index <= *last,
            Self::List(list) => list.contains(&page_index),
        }
    }
}

/// First-page and odd/even suppression rules.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Suppression {
    /// When `true`, page index zero receives no overlay.
    pub suppress_first_page: bool,
    /// Parity-based page selection.
    pub selection: PageSelection,
}

impl Suppression {
    /// Creates a suppression rule that draws on every page.
    pub const fn all() -> Self {
        Self {
            suppress_first_page: false,
            selection: PageSelection::All,
        }
    }
}

impl Default for Suppression {
    fn default() -> Self {
        Self::all()
    }
}

/// Where a single mark is placed in display coordinates.
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub enum WatermarkPosition {
    /// One mark at the geometric centre of the page.
    #[default]
    Center,
    /// One mark at the page centre, implicitly tilted by 45 degrees.
    ///
    /// The implicit tilt is added to the configured rotation; see
    /// [`Watermark::effective_rotation_degrees`].
    Diagonal,
    /// A repeating grid of marks.
    Tile {
        /// Horizontal distance between adjacent columns, in points.
        spacing_x: f32,
        /// Vertical distance between adjacent rows, in points.
        spacing_y: f32,
    },
    /// One mark at an exact display-coordinate origin.
    Absolute {
        /// Display `x` coordinate of the mark origin.
        x: f32,
        /// Display `y` coordinate of the mark origin.
        y: f32,
    },
}

/// A simple vector shape drawn as a rectangle centred on the mark origin.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct VectorMark {
    /// Rectangle width in points.
    pub width: f32,
    /// Rectangle height in points.
    pub height: f32,
    /// When `true` the rectangle is filled; otherwise it is stroked.
    pub filled: bool,
}

/// An image mark referencing an existing image XObject resource.
#[derive(Clone, Debug, PartialEq)]
pub struct ImageMark {
    /// Name of the image XObject in the page's `Resources /XObject` dictionary.
    pub xobject_name: String,
    /// Drawn width in points.
    pub width: f32,
    /// Drawn height in points.
    pub height: f32,
}

/// The content painted by a watermark.
#[derive(Clone, Debug, PartialEq)]
pub enum MarkContent {
    /// A text string painted with the configured font and size.
    Text(String),
    /// A simple vector rectangle.
    Vector(VectorMark),
    /// An existing image XObject.
    Image(ImageMark),
}

impl MarkContent {
    /// Convenience constructor for a text mark.
    pub fn text(text: impl Into<String>) -> Self {
        Self::Text(text.into())
    }
}

/// Font, size, colour, and opacity applied to a mark.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct WatermarkStyle {
    font: StandardFont,
    font_size: f32,
    color: TextColor,
    opacity: f32,
}

impl WatermarkStyle {
    /// Creates a style, validating size and opacity.
    pub fn new(
        font: StandardFont,
        font_size: f32,
        color: TextColor,
        opacity: f32,
    ) -> Result<Self, WatermarkError> {
        let style = Self {
            font,
            font_size,
            color,
            opacity,
        };
        validate_style(&style)?;
        Ok(style)
    }

    /// Creates a default style: Helvetica, 48 points, black, fully opaque.
    pub fn default_style() -> Self {
        Self {
            font: StandardFont::Helvetica,
            font_size: 48.0,
            color: TextColor::BLACK,
            opacity: 1.0,
        }
    }

    /// Font family.
    pub fn font(self) -> StandardFont {
        self.font
    }

    /// Font size in points.
    pub fn font_size(self) -> f32 {
        self.font_size
    }

    /// Mark colour.
    pub fn color(self) -> TextColor {
        self.color
    }

    /// Opacity in `0.0..=1.0`.
    pub fn opacity(self) -> f32 {
        self.opacity
    }
}

impl Default for WatermarkStyle {
    fn default() -> Self {
        Self::default_style()
    }
}

/// A fully specified watermark or background.
///
/// Instances are immutable after construction; use the `with_*` builder
/// methods to derive new values. Call [`validate`](Watermark::validate) or
/// [`render_watermark`] to check all invariants.
#[derive(Clone, Debug, PartialEq)]
pub struct Watermark {
    content: MarkContent,
    style: WatermarkStyle,
    position: WatermarkPosition,
    scale: f32,
    rotation_degrees: f32,
    placement: Placement,
    page_range: PageRange,
    suppression: Suppression,
}

impl Watermark {
    /// Creates a watermark with default style, position, scale, and policy.
    pub fn new(content: MarkContent) -> Self {
        Self {
            content,
            style: WatermarkStyle::default(),
            position: WatermarkPosition::default(),
            scale: 1.0,
            rotation_degrees: 0.0,
            placement: Placement::Front,
            page_range: PageRange::default(),
            suppression: Suppression::default(),
        }
    }

    /// Sets the mark style.
    pub fn with_style(mut self, style: WatermarkStyle) -> Self {
        self.style = style;
        self
    }

    /// Sets the mark placement.
    pub fn with_position(mut self, position: WatermarkPosition) -> Self {
        self.position = position;
        self
    }

    /// Sets the uniform scale applied about each mark's origin.
    pub fn with_scale(mut self, scale: f32) -> Self {
        self.scale = scale;
        self
    }

    /// Sets the configured rotation in degrees.
    pub fn with_rotation_degrees(mut self, rotation_degrees: f32) -> Self {
        self.rotation_degrees = rotation_degrees;
        self
    }

    /// Sets whether the overlay is painted in front of or behind content.
    pub fn with_placement(mut self, placement: Placement) -> Self {
        self.placement = placement;
        self
    }

    /// Sets the page range the watermark applies to.
    pub fn with_page_range(mut self, page_range: PageRange) -> Self {
        self.page_range = page_range;
        self
    }

    /// Sets the suppression rule.
    pub fn with_suppression(mut self, suppression: Suppression) -> Self {
        self.suppression = suppression;
        self
    }

    /// Painted content.
    pub fn content(&self) -> &MarkContent {
        &self.content
    }

    /// Mark style.
    pub fn style(&self) -> WatermarkStyle {
        self.style
    }

    /// Mark placement.
    pub fn position(&self) -> WatermarkPosition {
        self.position
    }

    /// Uniform scale.
    pub fn scale(&self) -> f32 {
        self.scale
    }

    /// Configured rotation in degrees.
    pub fn rotation_degrees(&self) -> f32 {
        self.rotation_degrees
    }

    /// Effective rotation in degrees, including the implicit diagonal tilt.
    pub fn effective_rotation_degrees(&self) -> f32 {
        let diagonal = if matches!(self.position, WatermarkPosition::Diagonal) {
            45.0
        } else {
            0.0
        };
        self.rotation_degrees + diagonal
    }

    /// Front/behind placement policy.
    pub fn placement(&self) -> Placement {
        self.placement
    }

    /// Page range.
    pub fn page_range(&self) -> &PageRange {
        &self.page_range
    }

    /// Suppression rule.
    pub fn suppression(&self) -> Suppression {
        self.suppression
    }

    /// Returns `true` when the watermark is selected for `page_index`.
    ///
    /// This combines the page range with first-page and odd/even suppression;
    /// it does not itself check the index against a document's page count.
    pub fn includes_page(&self, page_index: usize) -> bool {
        if self.suppression.suppress_first_page && page_index == 0 {
            return false;
        }
        let one_based = page_index + 1;
        match self.suppression.selection {
            PageSelection::All => {}
            PageSelection::Odd => {
                if one_based.is_multiple_of(2) {
                    return false;
                }
            }
            PageSelection::Even => {
                if !one_based.is_multiple_of(2) {
                    return false;
                }
            }
            PageSelection::Alternate { every, offset } => {
                if every == 0 || page_index < offset || !(page_index - offset).is_multiple_of(every)
                {
                    return false;
                }
            }
        }
        self.page_range.contains(page_index)
    }

    /// Validates every configurable value in the watermark.
    pub fn validate(&self) -> Result<(), WatermarkError> {
        validate_style(&self.style)?;

        if !self.scale.is_finite() || self.scale <= 0.0 {
            return Err(WatermarkError::InvalidScale(self.scale));
        }
        if !self.rotation_degrees.is_finite() || self.rotation_degrees.abs() > 360.0 {
            return Err(WatermarkError::InvalidRotation(self.rotation_degrees));
        }

        match &self.content {
            MarkContent::Text(text) => {
                if text.is_empty() {
                    return Err(WatermarkError::EmptyText);
                }
            }
            MarkContent::Vector(shape) => {
                if !shape.width.is_finite() || shape.width <= 0.0 {
                    return Err(WatermarkError::InvalidVectorSize {
                        field: "width",
                        value: shape.width,
                    });
                }
                if !shape.height.is_finite() || shape.height <= 0.0 {
                    return Err(WatermarkError::InvalidVectorSize {
                        field: "height",
                        value: shape.height,
                    });
                }
            }
            MarkContent::Image(image) => {
                if !valid_pdf_name(&image.xobject_name) {
                    return Err(WatermarkError::InvalidImageName(image.xobject_name.clone()));
                }
                if !image.width.is_finite() || image.width <= 0.0 {
                    return Err(WatermarkError::InvalidCoordinate {
                        field: "image width",
                        value: image.width,
                    });
                }
                if !image.height.is_finite() || image.height <= 0.0 {
                    return Err(WatermarkError::InvalidCoordinate {
                        field: "image height",
                        value: image.height,
                    });
                }
            }
        }

        match self.position {
            WatermarkPosition::Tile {
                spacing_x,
                spacing_y,
            } => {
                if !spacing_x.is_finite() || spacing_x < 1.0 {
                    return Err(WatermarkError::InvalidTileSpacing {
                        axis: "x",
                        value: spacing_x,
                    });
                }
                if !spacing_y.is_finite() || spacing_y < 1.0 {
                    return Err(WatermarkError::InvalidTileSpacing {
                        axis: "y",
                        value: spacing_y,
                    });
                }
            }
            WatermarkPosition::Absolute { x, y } => {
                if !x.is_finite() {
                    return Err(WatermarkError::InvalidCoordinate {
                        field: "x",
                        value: x,
                    });
                }
                if !y.is_finite() {
                    return Err(WatermarkError::InvalidCoordinate {
                        field: "y",
                        value: y,
                    });
                }
            }
            WatermarkPosition::Center | WatermarkPosition::Diagonal => {}
        }

        if let PageRange::RangeInclusive { first, last } = self.page_range
            && first > last
        {
            return Err(WatermarkError::InvalidPageRange { first, last });
        }

        Ok(())
    }

    /// Computes the display-coordinate origin of every mark for a page.
    fn placements(
        &self,
        display_width: f32,
        display_height: f32,
    ) -> Result<Vec<(f32, f32)>, WatermarkError> {
        match self.position {
            WatermarkPosition::Center | WatermarkPosition::Diagonal => {
                Ok(vec![(display_width / 2.0, display_height / 2.0)])
            }
            WatermarkPosition::Absolute { x, y } => Ok(vec![(x, y)]),
            WatermarkPosition::Tile {
                spacing_x,
                spacing_y,
            } => {
                let columns = ((display_width / spacing_x).ceil() as usize).max(1);
                let rows = ((display_height / spacing_y).ceil() as usize).max(1);
                let count = columns.saturating_mul(rows);
                if count > MAX_MARKS {
                    return Err(WatermarkError::TooManyMarks { count });
                }
                let mut placements = Vec::with_capacity(count);
                for row in 0..rows {
                    for column in 0..columns {
                        placements.push((
                            column as f32 * spacing_x + spacing_x / 2.0,
                            row as f32 * spacing_y + spacing_y / 2.0,
                        ));
                    }
                }
                Ok(placements)
            }
        }
    }
}

fn validate_style(style: &WatermarkStyle) -> Result<(), WatermarkError> {
    if !style.font_size.is_finite() || style.font_size <= 0.0 || style.font_size > 4096.0 {
        return Err(WatermarkError::InvalidFontSize(style.font_size));
    }
    if !style.opacity.is_finite() || !(0.0..=1.0).contains(&style.opacity) {
        return Err(WatermarkError::InvalidOpacity(style.opacity));
    }
    Ok(())
}

/// Returns `true` when `name` is a safe, non-empty PDF name token body.
fn valid_pdf_name(name: &str) -> bool {
    if name.is_empty() {
        return false;
    }
    name.bytes().all(|byte| {
        byte > b' '
            && !matches!(
                byte,
                b'/' | b'(' | b')' | b'<' | b'>' | b'[' | b']' | b'{' | b'}' | b'%' | b'#'
            )
    })
}

/// Approximates the rendered width of text using a deterministic advance.
fn approximate_width(text: &str, style: WatermarkStyle) -> f32 {
    text.chars().count() as f32 * style.font_size * style.font.average_advance()
}

/// Formats a number for a content stream without locale or exponent surprises.
fn format_num(value: f32) -> String {
    if value == 0.0 {
        return "0".to_string();
    }
    format!("{value}")
}

